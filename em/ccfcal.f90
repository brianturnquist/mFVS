!=======================================================!
!   Compute individual tree crown competition factors   !
!=======================================================!
! EM $Id$
subroutine CCFCAL(ISPC,D,H,JCR,P,LTHIN,CCFT,CRWDTH,MODE)
  implicit none

  !  THIS ROUTINE COMPUTES CROWN WIDTH AND CCF FOR INDIVIDUAL TREES.
  !  CALLED FROM DENSE, REGENT, PRTRLS, SSTAGE, AND CVCW.

  !  CROWN WIDTH EQUATIONS ARE FROM ANALYSIS BY NICK CROOKSTON USING
  !  DATA FROM RENATE BUSH.
  !  THESE CROWN WIDTH EQUATIONS ARE NO LONGER USED, REPLACED BY
  !  SUBROUTINE **CWCALC**

  ! Common blocks
  include 'PRGPRM.f90'
  include 'CONTRL.f90'
  include 'PLOT.f90'

  !  ARGUMENT DEFINITIONS:
  !    ISPC = NUMERIC SPECIES CODE
  !       D = DIAMETER AT BREAST HEIGHT
  !       H = TOTAL TREE HEIGHT
  !     JCR = CROWN RATIO IN PERCENT (0-100)
  !       P = TREES PER ACRE
  !   LTHIN = .TRUE. IF THINNING HAS JUST OCCURRED
  !         = .FALSE. OTHERWISE
  !    CCFT = CCF REPRESENTED BY THIS TREE
  !  CRWDTH = CROWN WIDTH OF THIS TREE
  !    MODE = 1 IF ONLY NEED CCF RETURNED
  !           2 IF ONLY NEED CRWDTH RETURNED

  !  DIMENSION AND DATA STATEMENTS FOR INTERNAL VARIABLES.

  !     CCF COEFFICIENTS FOR TREES THAT ARE GREATER THAN 10.0 IN. DBH:
  !      RD1 -- CONSTANT TERM IN CROWN COMPETITION FACTOR EQUATION,
  !             SUBSCRIPTED BY SPECIES
  !      RD2 -- COEFFICIENT FOR SUM OF DIAMETERS TERM IN CROWN
  !             COMPETITION FACTOR EQUATION,SUBSCRIPTED BY SPECIES
  !      RD3 -- COEFFICIENT FOR SUM OF DIAMETER SQUARED TERM IN
  !             CROWN COMPETITION EQUATION, SUBSCRIPTED BY SPECIES

  !     CCF COEFFICIENTS FOR TREES THAT ARE LESS THAN 1.0 IN. DBH:
  !      RDA -- MULTIPLIER.
  !      RDB -- EXPONENT.  CCF(I) = RDA*DBH**RDB

  !     B1  = BIAS CORRECTION COEFFICIENT
  !     B2  = CONSTANT TERM
  !     B3  = LOG-NATURAL OF CROWN LENGTH COEFFICIENT
  !     B4  = LOG-NATURAL OF DBH COEFFICIENT
  !     B5  = LOG-NATURAL OF TOTAL TREE HEIGHT COEFFICIENT
  !     B6  = LOG-NATURAL OF BASAL AREA COEFFICIENT

  ! Variables
  logical :: LTHIN
  real    :: CCFT,CRWDTH,P,D,H,BAREA,CL
  integer :: MODE,JCR,ISPC
  real    :: RD1(MAXSP),RD2(MAXSP),RD3(MAXSP),RDA(MAXSP),RDB(MAXSP)
  real    :: B1(MAXSP),B2(MAXSP),B3(MAXSP),B4(MAXSP),B5(MAXSP),B6(MAXSP)

  !  SPECIES ORDER:
  !   1=WB,  2=WL,  3=DF,  4=LM,  5=LL,  6=RM,  7=LP,  8=ES,
  !   9=AF, 10=PP, 11=GA, 12=AS, 13=CW, 14=BA, 15=PW, 16=NC,
  !  17=PB, 18=OS, 19=OH

  !  SPECIES EXPANSION
  !  LM USES IE LM (ORIGINALLY FROM TT VARIANT)
  !  LL USES IE AF (ORIGINALLY FROM NI VARIANT)
  !  RM USES IE JU (ORIGINALLY FROM UT VARIANT)
  !  AS,PB USE IE AS (ORIGINALLY FROM UT VARIANT)
  !  GA,CW,BA,PW,NC,OH USE IE CO (ORIGINALLY FROM CR VARIANT)

  !  SOURCES OF COEFFICIENTS:
  !     1 = PAINE AND HANN TABLE 2: WESTERN WHITE PINE
  !     2 = PAINE AND HANN TABLE 2: SUGAR PINE
  !     3 = PAINE AND HANN TABLE 2: DOUGLAS-FIR
  !     4 =
  !     5 =
  !     6 =
  !     7 = NORTHERN IDAHO VARIANT INT-133 TABLE 8: LODGEPOLE PINE
  !     8 = NORTHERN IDAHO VARIANT INT-133 TABLE 8: ENGELMANN SPRUCE
  !     9 = PAINE AND HANN TABLE 2: RED FIR
  !    10 = PAINE AND HANN TABLE 2: PONDEROSA PINE
  !    18 = PAINE AND HANN TABLE 2: CALIFORNIA BLACK OAK

  !      PAINE AND HANN, 1982. MAXIMUM CROWN WIDTH EQUATIONS FOR
  !        SOUTHWESTERN OREGON TREE SPECIES. RES PAP 46, FOR RES LAB
  !        SCH FOR, OSU, CORVALLIS. 20PP.

  !      WYKOFF, CROOKSTON, STAGE, 1982. USER'S GUIDE TO THE STAND
  !        PROGNOSIS MODEL. GEN TECH REP INT-133. OGDEN, UT:
  !        INTERMOUNTAIN FOREST AND RANGE EXP STN. 112P.

  data RD1/  .0186,  .0392,  .0388, .01925,    .03, .01925,&
       &.01925,    .03,  .0172,  .0219,    .03,    .03,    .03,&
       &.03,    .03,    .03,    .03,  .0204,    .03/
  data RD2/  .0146,  .0180,  .0269, .01676,  .0216, .01676,&
       &.01676,  .0173, .00876,  .0169,  .0215,  .0238,  .0215,&
       &.0215,  .0215,  .0215,  .0238,  .0246,  .0215/
  data RD3/ .00288, .00207, .00466, .00365, .00405, .00365,&
       &.00365, .00259, .00112, .00325, .00363, .00490, .00363,&
       &.00363, .00363, .00363, .00490,  .0074, .00363/
  data RDA/&
       &0.009884, 0.007244, 0.017299, 0.009187, 0.011402, 0.009187,&
       &0.009187, 0.007875, 0.011402, 0.007813, 0.011109, 0.008915,&
       &0.011109, 0.011109, 0.011109, 0.011109, 0.008915, 0.011109,&
       &0.011109/
  data RDB/&
       &1.6667,  1.8182,  1.5571,  1.7600,  1.7560,  1.7600,&
       &1.7600,  1.7360,  1.7560,  1.7780,  1.7250,  1.7800,&
       &1.7250,  1.7250,  1.7250,  1.7250,  1.7800,  1.7250,&
       &1.7250/

  !  CROWN WIDTH
  !  NOTE: 1=WB USES WL, 18=OS USES LP

  data B1/&
       &1.02478, 1.02478, 1.01685, 1.03992, 1.02886, 1.03992,&
       &1.03992, 1.02687, 1.02886, 1.02687, 1.02460, 1.03597,&
       &1.02460, 1.02460, 1.02460, 1.02460, 1.03597, 1.03992,&
       &1.02460/
  data B2/&
       &0.99889, 0.99889, 1.48372, 1.58777, 1.01255, 1.58777,&
       &1.58777, 1.28027, 1.01255, 1.49085, 1.35223, 1.46111,&
       &1.35223, 1.35223, 1.35223, 1.35223, 1.46111, 1.58777,&
       &1.35223/
  data B3/&
       &0.19422, 0.19422, 0.27378, 0.30812, 0.30374, 0.30812,&
       &0.30812, 0.22490, 0.30374, 0.18620, 0.24844, 0.26289,&
       &0.24844, 0.24844, 0.24844, 0.24844, 0.26289, 0.30812,&
       &0.24844/
  data B4/&
       &0.59423, 0.59423, 0.49646, 0.64934, 0.37093, 0.64934,&
       &0.64934, 0.47075, 0.37093, 0.68272, 0.41212, 0.18779,&
       &0.41212, 0.41212, 0.41212, 0.41212, 0.18779, 0.64934,&
       &0.41212/
  data B5/&
       &-0.09078,-0.09078,-0.18669,-0.38964,-0.13731,-0.38964,&
       &-0.38964,-0.15911,-0.13731,-0.28242,-0.10436, 0.00000,&
       &-0.10436,-0.10436,-0.10436,-0.10436, 0.00000,-0.38964,&
       &-0.10436/
  data B6/&
       &-0.02341,-0.02341,-0.01509, 0.00000, 0.00000, 0.00000,&
       &0.00000, 0.00000, 0.00000, 0.00000, 0.03539, 0.00000,&
       &0.03539, 0.03539, 0.03539, 0.03539, 0.00000, 0.00000,&
       &0.03539/

  !  INITIALIZE RETURN VARIABLES.

  CCFT = 0.
  CRWDTH = 0.

  !  COMPUTE CCF

  if (MODE.eq.1) then
     select case (ISPC)
     case(5)
        if (D.ge.10.0) then
           CCFT = RD1(ISPC) + D*RD2(ISPC) + D*D*RD3(ISPC)
        else
           CCFT = RDA(ISPC) * (D**RDB(ISPC))
        end if

     case(1:4,6:10,12,17,18)
        if (D .ge.1.0) then
           CCFT = RD1(ISPC) + D*RD2(ISPC) + D*D*RD3(ISPC)
        else if (D .gt.0.1) then
           CCFT = RDA(ISPC) * (D**RDB(ISPC))
        else
           CCFT = 0.001
        end if

     case(11,13:16,19)
        if (D .ge.10.0) then
           CCFT = RD1(ISPC) + D*RD2(ISPC) + D*D*RD3(ISPC)
        else if (D .gt.0.1) then
           CCFT = RDA(ISPC) * (D**RDB(ISPC))
        else
           CCFT = 0.001
        end if
     end select
  end if
  CCFT = CCFT * P

  !  COMPUTE CROWN WIDTH.

  if (JCR .le.0) go to 100
  if (MODE.eq.2) then
     CL = FLOAT(JCR)*H*.01
     BAREA = BA
     if (LTHIN.or.LFIRE) BAREA = OLDBA
     if (BAREA.le.0..or. CL.le.0..or. H.le.0..or.D.le.0.)goto 100

     if (BAREA.le.1.)BAREA = 1.
     CRWDTH = B1(ISPC)*EXP(B2(ISPC)+B3(ISPC)*ALOG(CL)+B4(ISPC)*&
          &ALOG(D)+B5(ISPC)*ALOG(H)+B6(ISPC)*ALOG(BAREA))

     if (CRWDTH .gt.99.9) CRWDTH = 99.9
  end if

  100 continue
  return
end
