!===============!
!   em : rcon   !
!===============!
! EM $Id$
subroutine RCON
  implicit none

  !  MOST OF THE MODELS IN THE PROGNOSIS PROGRAM CONTAIN TERMS
  !  FOR VARIABLES SUCH AS HABITAT TYPE, SLOPE, ASPECT, ELEVATION,
  !  AND GEOGRAPHIC LOCATION (FOREST) THAT ARE CONSTANT FOR THE
  !  DURATION OF ANY STAND PROJECTION.  THIS SUBROUTINE IS CALLED
  !  BY **CRATET** BEFORE MODEL CALIBRATION TO EVALUATE THE ABOVE
  !  EFFECTS FOR THE SPECIFIED CONDITIONS.  THESE EFFECTS ARE THEN
  !  LOADED INTO VECTORS THAT ARE SUBSCRIPTED BY SPECIES.

  ! Common blocks
  include 'PRGPRM.f90'
  include 'PLOT.f90'
  include 'ARRAYS.f90'
  include 'COEFFS.f90'
  include 'CONTRL.f90'
  include 'OUTCOM.f90'
  include 'HTCAL.f90'

  ! Variables
  logical :: DEBUG
  integer :: IHCODE(122),IDTYPE

  !  SPECIES ORDER:
  !   1=WB,  2=WL,  3=DF,  4=LM,  5=LL,  6=RM,  7=LP,  8=ES,
  !   9=AF, 10=PP, 11=GA, 12=AS, 13=CW, 14=BA, 15=PW, 16=NC,
  !  17=PB, 18=OS, 19=OH

  !  SPECIES EXPANSION
  !  LM USES IE LM (ORIGINALLY FROM TT VARIANT)
  !  LL USES IE AF (ORIGINALLY FROM NI VARIANT)
  !  RM USES IE JU (ORIGINALLY FROM UT VARIANT)
  !  AS,PB USE IE AS (ORIGINALLY FROM UT VARIANT)
  !  GA,CW,BA,PW,NC,OH USE IE CO (ORIGINALLY FROM CR VARIANT)

  !  IHCODE IS A LIST OF THE HABITAT TYPES IN THE ORDER THAT THE
  !  HABITAT DEPENDENT COEFFICIENTS ARE LOADED FOR THE DIAMETER
  !  INCREMENT, MORTALITY, AND SMALL TREE GROWTH MODELS.  IDTYPE
  !  IS LOADED WITH THE SUBSCRIPT OF THE HABITAT TYPE INPUT FOR
  !  A PROJECTION.

  data IHCODE/&
       &10, 65, 70, 74, 79, 91, 92, 93, 95,100,&
       &110,120,130,140,141,161,170,171,172,180,&
       &181,182,200,210,220,221,230,250,260,261,&
       &262,280,281,282,283,290,291,292,293,310,&
       &311,312,313,315,320,321,322,323,330,331,&
       &332,340,350,360,370,371,400,410,430,440,&
       &450,460,461,470,480,591,610,620,624,625,&
       &630,632,640,641,642,650,651,653,654,655,&
       &660,661,662,663,670,674,690,691,692,700,&
       &710,720,730,731,732,733,740,750,751,770,&
       &780,790,791,792,810,820,830,832,850,860,&
       &870,900,910,920,930,940,950,999,4*0 /

  !  CHECK FOR DEBUG.

  call DBCHK (DEBUG,'RCON',4,ICYC)

  !  DECODE THE HABITAT CLASSES FOR THE DIAMETER GROWTH MODEL.

  do IDTYPE = 1,117
     if (ICL5.eq.IHCODE(IDTYPE)) go to 6
     5 continue
  end do
  IDTYPE = 118
  6 continue

  !  CALL SPECIAL ENTRIES WITHIN GROWTH MODELS TO LOAD SITE
  !  DEPENDENT COEFFICIENTS.

  call DGCONS(IDTYPE)
  call HTCONS
  call REGCON
  call MORCON
  call CRCONS

  !  PRINT DEBUG INFO IF REQUESTED.

  if (.not.DEBUG) return
  write(JOSTND,9001)
  write(JOSTND,9002) 'DGCON',DGCON
  write(JOSTND,9002) 'ATTEN',ATTEN
  write(JOSTND,9002) 'HTCON',HTCON
  write(JOSTND,9002) 'RHCON',RHCON
  write(JOSTND,9002) 'CRCON',CRCON
  9001 format(/,' DEBUG TABLE SHOWING VALUES OF MODEL CONSTANTS',&
       &' BY SPECIES')
  9002 format(1X,A,4X,((T11,11F10.4)))
  write(JOSTND,9003) H2COF,HDGCOF
  9003 format(/' H2COF=',F10.4,',  HDGCOF=',F10.4)
  return
end
