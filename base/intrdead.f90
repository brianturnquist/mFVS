!=====================!
!   base : intrdead   !
!=====================!
! BASE $Id$
subroutine INTRDEAD (I,ITH)
  implicit none

  !  CALLED FROM **INTREE** AND **ORG_INTREE** WHEN THE TREE RECORD JUST
  !  READ INTO POSITION I IS A DEAD TREE (TREE HISTORY CODE ITH = 6-9).
  !  THE CALLER HAS ALREADY DECREMENTED IREC2. THIS ROUTINE COPIES THE TREE
  !  ATTRIBUTES THAT BOTH READERS SET FROM POSITION I TO POSITION IREC2 AT
  !  THE BOTTOM OF THE ARRAYS, AND RESETS THEM AT POSITION I. ATTRIBUTES
  !  THAT ONLY **INTREE** READS (LBIRTH, CULL, DECAYCD, WDLDSTEM) ARE
  !  MOVED BY **INTREE** BEFORE IT CALLS THIS ROUTINE.

  !  TREES WITH HISTORY CODES 6,7 ARE RECENT DEAD (GET IMC()=7)
  !  TREES WITH HISTORY CODES 8,9 ARE OLDER  DEAD (GET IMC()=9)

  ! Common blocks
  include 'PRGPRM.f90'
  include 'ARRAYS.f90'
  include 'CONTRL.f90'
  include 'STDSTK.f90'

  ! Variables
  integer :: I,ITH,I3

  ITRE(IREC2) = ITRE(I)
  IDTREE(IREC2) = IDTREE(I)

  !  NOTE: INFLATION OF DEAD TREE PROB'S IS IN NOTRE.  CROWN RATIOS
  !        FOR TREES LESS THAN 3 INCHES ARE SET ZERO IN CRATET.

  PROB(IREC2) = PROB(I)
  DBH(IREC2) = DBH(I)
  DG(IREC2) = DG(I)
  HT(IREC2) = HT(I)
  ITRUNC(IREC2) = ITRUNC(I)
  NORMHT(IREC2) = NORMHT(I)
  ICR(IREC2) = ICR(I)
  ISP(IREC2) = ISP(I)
  ISPECL(IREC2) = ISPECL(I)
  DEFECT(IREC2) = DEFECT(I)
  IMC(IREC2) = 7
  if (ITH.eq.8 .or. ITH.eq.9) IMC(IREC2) = 9
  ABIRTH(IREC2) = ABIRTH(I)
  KUTKOD(IREC2) = KUTKOD(I)
  do I3 = 1,6
     DAMSEV(I3,IREC2) = DAMSEV(I3,I)
  end do

  ! RESET ARRAY VALUES TO ZERO IN CASE THIS IS THE LAST RECORD
  ! IN THE INPUT DATA --- DON'T WANT THESE VALUES HANGING AROUND
  ! WHERE THEY AREN'T SUPPOSED TO BE.  GD 5/10/96

  PROB(I) = 0.
  DBH(I) = 0.
  DG(I) = 0.
  HT(I) = 0.
  ITRUNC(I) = 0
  NORMHT(I) = 0
  ICR(I) = 0
  ISP(I) = 0
  ISPECL(I) = 0
  DEFECT(I) = 0
  IDTREE(I) = 0
  HTG(I) = 0.
  ITRE(I) = 0
  NORMHT(I) = 0
  PDBH(I) = 0.
  PHT(I) = 0.
  ZRAND(I) = -999.
  ABIRTH(I) = 0.
  KUTKOD(I) = 0
  do I3 = 1,6
     DAMSEV(I3,I) = 0
  end do

  return
end subroutine INTRDEAD
