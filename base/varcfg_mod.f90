! BASE $Id$

!     RUNTIME COPIES OF THE PRGPRM VARIANT CONSTANTS (SP04).
!
!     CFG_VARIANTCD AND CFG_LMETRICVAR HOLD THE PROGRAM'S COMPILE-TIME
!     VARIANTCD AND LMETRICVAR. THEY ARE INITIALIZED WHEN THE PROGRAM IS
!     LOADED, SO THEY ARE SET BEFORE ANY ROUTINE READS THEM, INCLUDING
!     GRINIT, FILOPN AND THE FVS ENTRY POINTS. A ROUTINE THAT NEEDED A
!     VARIANT VALUE IN A CONSTANT CONTEXT (A PARAMETER STATEMENT, A CASE
!     SELECTOR OR A DATA-DRIVEN BANK OFFSET) READS THESE INSTEAD.
!
!     VARACD IN COMMON CONTRL IS UNCHANGED; IT IS ONLY SET ONCE GRINIT HAS
!     RUN. NO VALUE HERE IS CHANGED AFTER LOADING.
!
!     PRGPRM IS INCLUDED BELOW, SO THIS MODULE IS COMPILED IN EACH VARIANT'S
!     BUILD DIRECTORY, ALONGSIDE THE VARIANT'S OTHER PRGPRM CONSUMERS.

module VARCFG_MOD
  implicit none
  private

  include 'PRGPRM.f90'

  character(len=2), public :: CFG_VARIANTCD = VARIANTCD
  logical,          public :: CFG_LMETRICVAR = LMETRICVAR

end module VARCFG_MOD
