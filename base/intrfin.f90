!====================!
!   base : intrfin   !
!====================!
! BASE $Id$
subroutine INTRFIN (IPTKNT,ISCRN,DBSKODE,LKECHO,DEBUG)
  implicit none

  !  CALLED FROM **INTREE** AND **ORG_INTREE** AT THE END OF THE TREE DATA
  !  ON THIS FILE: SAVES THE PLOT COUNT, LIMITS THE SITE TREE COUNT AND
  !  WRITES THE SCREENING, ROW COUNT AND DEBUG SUMMARIES.

  !  IPTKNT  -- NUMBER OF PLOTS COUNTED
  !  ISCRN   -- NUMBER OF TREE RECORDS SCREENED OUT BY THE DIAMETER SCREEN
  !  DBSKODE -- DATABASE RETURN CODE FROM **DBSTREESIN** (-1 = DATABASE)

  ! Common blocks
  include 'PRGPRM.f90'
  include 'CONTRL.f90'
  include 'PLOT.f90'

  ! Variables
  integer :: IPTKNT,ISCRN,I,J
  integer*4 :: DBSKODE
  logical :: LKECHO,DEBUG

  LSTKNT = IPTKNT + 1

  if (NSITET .gt. MAXSTR)NSITET = MAXSTR

  !   CALL INTREX TO READ ANY ADDITIONAL DATA THAT MAY BE NEEDED BY
  !   EXTENSIONS.

  !***  CALL INTREX (IDTREE)

  if (ISCRN .gt. 0) write(JOSTND,901) ISCRN
  901 format(/,T12,'**** NOTE: ',I5,' TREE RECORDS HAVE BEEN', &
       & ' SCREENED OUT BY THE DIAMETER SCREEN.')
  if ((DBSKODE.eq.-1).and.LKECHO)write (JOSTND,940) IRECRD
  940 format (T12,'NUMBER ROWS PROCESSED:',I5)
  if (DEBUG) then
     write(JOSTND,945) IRECRD,IPTKNT,DBSKODE
     945 format (/' LEAVING SUBROUTINE INTREE.   RECORDS READ=',I5, &
          & '; PLOTS COUNTED = ',I5,'; DBSKODE=',I4)
     if (NSITET.gt.0)write(JOSTND,950)((SITETR(I,J),J = 1,6),I = 1,NSITET)
     950 format(/' SITE INDEX TREES:',/,7X,'ISPC',7X,'DBH',8X,'HT', &
          & 7X,'AGE',4X,'T OR B',4X,'ON OFF',20(/,1X,F10.0,2F10.1,3F10.0))
  end if

  return
end subroutine INTRFIN
