!============================!
!   Compress the tree list   !
!============================!
! BASE $Id$
subroutine COMPRS (NCLAS,PN1)
  implicit none

  !     TREE LIST COMPRESSION ROUTINE FOR THE PROGNOSIS
  !     MODEL FOR STAND DEVELOPMENT.

  !     NICHOLAS L. CROOKSTON                     AUG 1979 & MAY 1980
  !     MARCH 1981: ADDED TRUNCATED TREE AND SUBPLOT COMPRESSION.
  !     APRIL/JUNE 1982: REWORKED THE SPLITTING RULES WITH ALBERT STAGE.
  !     NOV 1995: CHANGED TO USE SUM OF PROB AND TREES DYING IN AVERAGING.
  !     INT-FORESTRY SCIENCES LABORATORY-MOSCOW, IDAHO

  !     THE GOAL OF THIS ROUTINE IS TO REDUCE THE LENGTH OF THE
  !     TREE ATTRIBUTE VECTORS FROM THEIR ORIGINIAL LENGTH (ITRN)
  !     TO THE LENGTH 'NCLAS'.

  !     THERE ARE TWO METHODS USED TO FIND THE CLASSES:

  !     METHOD 1: FIRST, DEFINE A LIST, WK3 (WITH LENGTH ITRN),
  !     OF THE SUM OF EACH TREE ATTRIBUTE (IE, SPECIES, DDS, ETC.)
  !     MULTIPLIED BY THE APPROPRIATE ATTRIBUTE WEIGHT. THEN,
  !     DEFINE THE CLASS BOUNDARYIES AS BEING AT THE MAXIMUM BREAKS
  !     IN WK3.

  !     METHOD 2: REDEFINE THE SCORE TO INCLUDE THE PRINCIPAL COMPONENTS
  !     OF THE VARIANCE IN THE RECORD ATTRIBUTES.  THEN FIND THE CLASS
  !     WHICH HAS THE GREATEST RANGE OF THE NEW SCORE AND SPLIT IT
  !     INTO TWO CLASSES.  REPEATE UNTIL THE NUMBER OF ADDITIONAL
  !     CLASSES DESIRED HAVE BEEN FOUND.

  !     UPON RETURN:
  !     1. THE TREE LIST LENGTH IS REDUCED
  !     2. THE SPECIES-ORDER SORT IS NOT ALIGNED.
  !     3. THE 'IND' DIAMETER SORT IS NOT ALIGNED AND THE MEMBERS
  !        OF IND INCLUDE NEGETIVE NUMBERS.
  !     4. THE VALUE OF ITRN IS EQUAL TO THE NUMBER OF TREES
  !        IN THE TREE LIST...ITRN=NCLAS.
  !     5. THE VALUE OF IREC1 IS EQUAL TO THE NEXT AVAILABLE
  !        TREE IN THE TREE LIST: IREC1=ITRN

  !     ARGUMENTS:
  !     NCLAS = THE NUMBER OF OUTPUT TREE RECORDS (CLASSES)
  !     PN1   = THE PROPORTION OF NCLAS FOUND USING METHOD 1
  !     RNGMIN= THE MIN WITHIN CLASS RANGE NEEDED TO CONTINUE SPLITTING.
  !     LDEBG = TRUE IF DEBUG OUTPUT IS DESIRED.
  !     JOSTND  = OUTPUT DATA SET REF. NUMBER FOR DEDUG MESSAGES.

  !     NOTEWORTHY INTERNAL VARIABLES:
  !     NCLS1 = THE NUMBER OF CLASSES FOUND USING METHOD 1
  !     NCLS2 = THE NUMBER OF CLASSES FOUND USING METHOD 2
  !     LTRNK = TRUE IF THE CURRENT CLASS IS A 'TRUNCATED-TREE' CLASS.

  ! Common blocks
  include 'PRGPRM.F77'
  include 'ARRAYS.F77'
  include 'CONTRL.F77'
  include 'PLOT.F77'
  include 'ESTREE.F77'
  include 'STDSTK.F77'

  ! Variables
  integer :: IDF44,IDF33,IDF22,IDF11,IDMR,II,ICL,IREC
  real    :: CRWDI,DF44,DF33,DF22,DF11,PHTI,PDBHI,PMCVI,PCFVI,WK2I,WK1I
  real    :: PMBVI,PROBI,PCTI,OLDPTI,HTGI,CFVI,MCFVI,SCFVI,BFVI,PSCVI
  real    :: XBAR,SSWC,TSSWC,PRANG,XSMAL,XRANG,X1,X2,DGI,DBHI,TERM1
  integer :: LN,I1,I2,ISIG,NCLS2,NCLS1,LEN2,LEN3,NCLAS,NRANK1,I,IJ
  integer :: IOBSRV,JOBSRV,J,JK,K,IZERS,LEN,NRANK,LEN1
  real    :: PN1,ALGTOL,RNGMIN,TTPRB,TTWK2,HTI,XICRI,X,CMRANG
  real    :: HT2TDBFI,HT2TDCFI,XNR,XIT,TXP,XP,DIV

  real    :: CULLI
  integer :: DECAYI,WDLDSTEMI

  real    :: ABVGRD_BIOI,MERCH_BIOI,CUBSAW_BIOI,FOLI_BIOI,ABVGRD_CARBI,MERCH_CARBI,CUBSAW_CARBI, &
       & FOLI_CARBI,CARB_FRACI

  parameter (NRANK = 5, NRANK1 = NRANK+1, LEN1 = NRANK1*(NRANK1+1)/2, &
       & LEN2 = NRANK*NRANK1/2,   LEN3 = NRANK*NRANK)

  double precision :: XTX(LEN2),EIVECT(LEN3),DTRN,XSUM(NRANK)
  double precision :: RMEANS(NRANK),STDDEV(NRANK),VARS(NRANK),OBSERV(NRANK)
  logical :: LDEBG,LTRNK,L2,LTWO
  equivalence (OBSERV,WK6)
  integer*4 :: IDCMP2
  data RNGMIN/0.00001/,ALGTOL/0.066/
  data IDCMP2/20000000/

  !     *******************     EXECUTION BEGINS     ********************

  !     CHECK FOR DEBUG.

  call DBCHK (LDEBG,'COMPRS',6,ICYC)

  !     IF THERE ARE FEWER TREES THAN REQUESTED CLASSES, RETURN.

  if (LDEBG) write (JOSTND,1) NCLAS,ITRN
  1 format (' IN COMPRS: NCLAS,ITRN=',2I6)
  if (NCLAS.ge.ITRN) return

  !     STEP2: CALCULATE THE INITIAL WEIGHTED SCORE FOR EACH TREE RECORD
  !            (AND COMPUTE SOME SUMS FOR DEBUG OUTPUT).

  TTPRB = 0.
  TTWK2 = 0.
  do I = 1,ITRN
     WK3(I) = 25.0*(PI*ISP(I)+ITRE(I))
     if (LDEBG) then
        TTPRB = TTPRB+PROB(I)
        TTWK2 = TTWK2+WK2(I)
     end if
     5 continue
  end do

  IF (LDEBG) WRITE (JOSTND,'('' SUM OF PROB (BEFORE)= '',F10.4,     &
       &                           '' SUM OF MORT= '',F10.4)') TTPRB,TTWK2

  !     STEP3: REFINE THE SCORE FOR EACH TREE RECORD.

  !     (A) COMPUTE THE CORELATION MATRIX OF SOME OF THE CLASS-
  !     IFICATION VARIABLES.

  !     FIRST, LET ME DEFINE THE VECTOR STORAGE MODE:
  !        CONSIDER THE FOLLOWING MATRIX, XTX:
  !             A    B    C
  !             D    E    F
  !             G    H    I
  !        WHERE: D=B, G=C, AND H=F, THAT IS, THE MATRIX IS SYMMETRIC.
  !     THEN, XTX IS STORED IN A VECTOR OF LENGTH N*(N+1)/2 (WHERE N IS
  !     THE DIMENSION OF THE MATRIX...WHICH IS EQUAL TO THE RANK ON A
  !     FULL RANK MATRIX), WITH ONE COLUMN STORED DIRECTLY AFTER
  !     THE OTHER: XTX = A, B, E, C, F, I.

  !     INITIALIZE XTX.

  do I = 1,NRANK
     XSUM(I) = 0D0
     10 continue
  end do
  do I = 1,LEN2
     XTX(I) = 0D0
     15 continue
  end do

  !     COMPUTE THE MEAN AND STANDARD DEVIATION OF ALL THE
  !     CLASSIFICATION VARIABLES.  THE CLASSIFICATION VARIABLES ARE:

  !     1.  HEIGHT  (HT)
  !     2.  MANAGEMENT CODE (IMC)
  !     3.  CROWN RATIO (ICR)
  !     4.  NATURAL LOG OF DIAMETER AT BREAST HEIGHT (DBH)
  !         (TEMPORARILY STORED IN WK4 UNTIL WEIGHTS ARE CALCULATED.)
  !     5.  DIAMETER GROWTH (DG)

  call MEANSD (HT,ITRN,RMEANS(1),VARS(1),STDDEV(1))
  if (STDDEV(1).lt.1D0) STDDEV(1) = 1D0
  do I = 1,ITRN
     WK4(I) = ICR(I)
     20 continue
  end do
  call MEANSD (WK4,ITRN,RMEANS(2),VARS(2),STDDEV(2))
  if (STDDEV(2).lt.0.1D-3) STDDEV(2) = 0.1D-3
  do I = 1,ITRN
     WK4(I) = IMC(I)
     25 continue
  end do
  call MEANSD (WK4,ITRN,RMEANS(3),VARS(3),STDDEV(3))
  if (STDDEV(3).lt.0.1D-3) STDDEV(3) = 0.1D-3
  do I = 1,ITRN
     WK4(I) = ALOG(DBH(I))
     30 continue
  end do
  call MEANSD (WK4,ITRN,RMEANS(4),VARS(4),STDDEV(4))
  if (STDDEV(4).lt.5D-3) STDDEV(4) = 5D-3
  call MEANSD (DG,ITRN,RMEANS(5),VARS(5),STDDEV(5))
  if (STDDEV(5).lt.0.02) STDDEV(5) = 0.02

  !     CENTER AND SCALE THE WEIGHTS.

  do I = 1,ITRN
     OBSERV(1) = (HT(I)-RMEANS(1))/STDDEV(1)
     OBSERV(2) = (FLOAT(ICR(I))-RMEANS(2))/STDDEV(2)
     OBSERV(3) = (FLOAT(IMC(I))-RMEANS(3))/STDDEV(3)
     OBSERV(4) = (WK4(I)-RMEANS(4))/STDDEV(4)
     OBSERV(5) = (DG(I)-RMEANS(5))/STDDEV(5)

     !     COMPUTE X*(TRANSPOSE X), STORE IN XTX.

     IJ = 0
     do IOBSRV = 1,NRANK
        do JOBSRV = 1,IOBSRV
           IJ = IJ+1
           XTX(IJ) = XTX(IJ)+OBSERV(IOBSRV)*OBSERV(JOBSRV)
           35 continue
        end do
        XSUM(IOBSRV) = XSUM(IOBSRV)+OBSERV(IOBSRV)
        40 continue
     end do
     60 continue
  end do
  if (LDEBG) write (JOSTND,61) (XSUM(I),I = 1,NRANK)
  61 format (' IN COMPRS, SUMS: ',5D20.10)

  !     SUBTRACT THE CROSS PRODUCT OF THE STANDARD DEVIATIONS.

  DTRN = ITRN
  IJ = 0
  do I = 1,NRANK
     do J = 1,I
        IJ = IJ+1
        XTX(IJ) = XTX(IJ)-XSUM(I)*XSUM(J)/DTRN
        62 continue
     end do
     63 continue
  end do

  !     NORMALIZE XTX TO OBTAIN THE CORRELATION MATRIX.

  DTRN = ITRN-1
  do I = 1,LEN2
     XTX(I) = XTX(I)/DTRN
     65 continue
  end do
  IJ = 0
  do I = 1,NRANK
     do J = 1,I
        IJ = IJ+1
        if (I.eq.J) XTX(IJ) = 1D0
        66 continue
     end do
     67 continue
  end do

  !     IF DEBUG IS DESIRED, PRINT THE CORRELATION MATRIX.

  if (LDEBG) write (JOSTND,70) NRANK,(XTX(I),I = 1,LEN2)
  70 format ( /' IN COMPRS: CORRELATIONS (WRITTEN IN VECTOR FORMAT)' &
       & ,' RANK = ',I2,5( /1X,5D20.12))

  !     (B) COMPUTE EIGENVALUES AND EIGENVECTORS.
  !         THE EIGENVALUES WILL BE STORED IN THE DIAGONAL ELEMENTS OF
  !         XTX, AND THE EIGENVECTORS WILL BE STORED IN EIVECT.
  !         NOTE: THE ROUTINE USED HERE IS FORM IBMS SCIENTIFIC SUB-
  !         ROUTINE PACKAGE OF 1966 VINTAGE (...REMEMBER THEN]).

  call EIGEN (XTX,EIVECT,NRANK,0)

  !     FIX THE SIGN OF THE FIRST AND SECOND EIGENVECTOR.

  if (EIVECT(4).lt.0.) then
     if (LDEBG) write (JOSTND,71)
     71 format (' IN COMPRS: SIGN CHANGE ON FIRST EIGENVECTOR.')
     do I = 1,NRANK
        EIVECT(I) = -EIVECT(I)
        72 continue
     end do
  end if
  if (EIVECT(7).gt.0.) then
     if (LDEBG) write (JOSTND,73)
     73 format (' IN COMPRS: SIGN CHANGE ON SECOND EIGENVECTOR.')
     do I = NRANK+1,(NRANK*2)
        EIVECT(I) = -EIVECT(I)
        74 continue
     end do
  end if

  if (LDEBG) write (JOSTND,69) ALGTOL
  69 format (' IN COMPRS: ALGTOL = ',E15.7)

  !     PRINT THE EIGENVALUES AND VECTORS, IF DESIRED.

  if (.not.LDEBG) goto 79
  write (JOSTND,75) (XTX(I+(I*I-I)/2),I = 1,NRANK)
  75 format ( /' IN COMPRS: EIGENVALUES: ',5D20.12)
  write (JOSTND,76) NRANK,(EIVECT(I),I = 1,LEN3)
  76 format ( /' IN COMPRS: EIGENVECTORS, RANK = ',I3,5( /1X,5D20.12))
  79 continue
  if (LDEBG) write (JOSTND,78) XTX(1)
  78 format (' IN COMPRS: FIRST EIGENVALUE = ',D20.12)

  !     C) SCALE EIGENVECTOR BY SIGMA X(K)

  JK = 0
  do J = 1,NRANK
     do K = 1,NRANK
        JK = JK+1
        EIVECT(JK) = EIVECT(JK)/STDDEV(K)
     end do
  end do

  !     (D) ADD A NORMALIZED SCORE FOR EACH TREE RECORD TO THE INITIAL
  !         SCORE.  GIVE THE INITIAL SCORE AN ADDITIONAL OVERALL WEIGHT.
  !         ADD 4 TO SHIFT THE ORIGIN TO THE MIN VALUE APPROXIMATED BY
  !         -4 (ON NORMALIZED SCALE).
  !         ALSO, CREATE A NEW SCORE BASED ON THE SECOND PRINCIPAL
  !         COMPONENT.

  do I = 1,ITRN
     HTI = real(HT(I)-RMEANS(1))
     XICRI = real(real(ICR(I))-RMEANS(2))
     X = real(real(IMC(I))-RMEANS(3))
     DBHI = real(WK4(I)-RMEANS(4))
     DGI = real(DG(I)-RMEANS(5))
     TERM1 = real((HTI  *EIVECT(1)) + &
          & (XICRI*EIVECT(2)) + &
          & (X    *EIVECT(3)) + &
          & (DBHI *EIVECT(4)) + &
          & (DGI  *EIVECT(5)) + 4.)
     WK3(I) = WK3(I) + TERM1
     WK4(I) = real((HTI  *EIVECT(6)) + &
          & (XICRI*EIVECT(7)) + &
          & (X    *EIVECT(8)) + &
          & (DBHI *EIVECT(9)) + &
          & (DGI  *EIVECT(10)))
  end do

  !     STEP4:  SORT 'IND' ON 'WK3' USING RDPSRT (DESCENDING ORDER)

  if (ITRN .gt. 0) call RDPSRT (ITRN,WK3,IND,.true.)
  !*    IF (LDEBG) WRITE (JOSTND,95) (I,WK3(IND(I)),IND(I),I=1,ITRN)
  !* 95 FORMAT (' IN COMPRS: INITIAL WEIGHTS = '/((I6,1X,E16.8,1X,I5)))

  !     STEP5:  FIND THE MAXIMUM DIFFERENCES IN THE WORK ARRAY.  THE
  !     POINTS OF MAXIMUM DIFFERENCES WILL DICTATE
  !     WHERE THE CLASS BREAKS ARE.

  !     (A) CALCULATE THE DIFFERENCES.

  IZERS = 0
  I = IND(1)
  X1 = WK3(I)
  do J = 2,ITRN
     I = IND(J)
     X2 = WK3(I)
     WK6(J-1) = X1-X2
     if (WK6(J-1).le.ALGTOL) IZERS = IZERS+1
     X1 = X2
     110 continue
  end do

  !     (B)  CALCULATE THE NUMBER OF CLASSES FOUND BY METHOD 1.

  NCLS1 = INT(real(NCLAS)*PN1+.5)
  ISIG = ITRN-IZERS
  if (ISIG.lt.NCLS1)  NCLS1 = ISIG
  if (NCLS1.lt.1) NCLS1 = 1
  if (NCLS1.gt.NCLAS) NCLS1 = NCLAS

  !     (C)  CREATE A SORTED LIST OF POINTERS WHICH POINT TO THE
  !          DIFFERENCES IN DESCENDING ORDER.

  call RDPSRT(ITRN-1,WK6,IND1,.true.)
  !*    IF (LDEBG) WRITE (JOSTND,112) (I,WK6(IND1(I)),IND1(I),I=1,ITRN-1)
  !*112 FORMAT (' IN COMPRS: 1ST SCORE DIFFS = '/((I6,1X,E16.8,1X,I5)))

  !     (D)  SORT THE FIRST 'NCLS1-1' MEMBERS OF THE POINTER LIST INTO
  !          ASCENDING ORDER.

  if (NCLS1.gt.1) call IQRSRT (IND1,NCLS1-1)
  IND1(NCLS1) = ITRN

  !     (E) CALCULATE THE NUMBER OF CLASSES TO BE FOUND BY METHOD 2.

  NCLS2 = NCLAS-NCLS1
  if (LDEBG) write (JOSTND,114) NCLAS,PN1,ITRN,NCLS1,NCLS2,RNGMIN
  114 format(' IN COMPRS: NCLAS=',I4,' PN1=',F5.2,' ITRN=',I4,' NCLS1=', &
       & I4,' NCLS2=',I4,' RNGMIN=',E14.6)

  !     STEP6:  DEFINE NCLS2 MORE CLASSES USING METHOD 2.

  !     (A) SKIP IF NCLS2 IS ZERO.

  if (NCLS2 .le. 0) goto 200

  !     (B) COMPUTE THE SCORE RANGE ON THE FIRST EIGENVECTOR PRODUCT
  !         WITHIN EACH CLASS AND THE NUMBER OF TREE RECORDS PER CLASS.

  I1 = 1
  do I = 1,NCLS1
     I2 = IND1(I)
     J = IND(I2)
     K = IND(I1)
     WK6(I) = WK3(K)-WK3(J)
     LEN = I2-I1+1
     IND2(I) = LEN

     !     COMPUTE THE RANGE ON THE SECOND EIGENVECTOR PRODUCT

     WK5(I) = CMRANG(LEN,IND(I1),WK4)
     !*    IF (LDEBG) WRITE (JOSTND,115) I,K,J,WK6(I),WK5(I)
     !*115 FORMAT (' IN COMPRS: I,K,J,WK6(I),WK5(I)=',3I5,2F10.3)
     I1 = I2+1
     120 continue
  end do

  !     (C) CREATE NEW CLASSES BY SPLITTING THE CLASSES WITH THE LARGEST
  !     RANGE.  THE SPLIT IS AT ONE OF THE RECORDS NEXT TO THE CLASS
  !     MID-RANGE.

  do K = 1,NCLS2

     !     FIND THE LARGEST RANGE

     IREC = 0
     XRANG = 0.
     do J = 1,NCLS1

        !     LET: XRANG BE THE RANGE OF THE LARGEST CLASS,
        !          L2 AND LTWO BE TRUE IF THE RANGE IN THE SECOND COMPONENT
        !          IS LARGER THAN IN THE FIRST, AND
        !          IREC POINT TO THE LARGEST CLASS.

        X = WK6(J)
        L2 = WK5(J).gt.X
        if (L2) X = WK5(J)
        if (X.le.XRANG) goto 130
        LTWO = L2
        XRANG = X
        IREC = J
        130 continue
     end do

     !*    IF (LDEBG) WRITE (JOSTND,131) LTWO,XRANG,IREC,LEN
     !*131 FORMAT (' IN COMPRS: LTWO,XRANG,IREC,LEN=',L3,F10.3,2I5)

     !     IF THE LARGEST RANGE IS VERY SMALL, THEN: EXIT THE SPLITTING
     !     LOOP (DO NOT DEFINE ANY MORE CLASSES VIA METHOD 2).

     if ((XRANG.le.RNGMIN).or.(IREC.eq.0)) goto 195
     LEN = IND2(IREC)
     JK = 0
     I1 = IND1(IREC)-LEN+1

     !     IF LTWO IS TRUE (OPERATING ON SECOND EIGENVECTOR); THEN: SORT
     !     THE WITHIN CLASS POINTERS ON THE SECOND SCORE.

     if (LTWO) call RDPSRT (LEN,WK4,IND(I1),.false.)

     !     FIND THE CLASS MID-RANGE.

     !     LET LEN INITIALLY EQUAL HALF THE NUMBER OF RECORDS IN THE CLASS.
     !     I, POINTS TO THE LAST RECORD IN THE CLASS.
     !     REMEMBER THAT THE LIST IS SORTED IN DESCENDING ORDER.  THEREFORE,
     !     THE MID-RANGE POINT IS HALF THE RANGE PLUS THE LAST OBSERVATION.

     I2 = IND1(IREC)
     I = IND(I2)
     XSMAL = WK3(I)
     if (LTWO) XSMAL = WK4(I)

     !     IF THERE ARE ONLY 2 RECORDS IN THE CLASS, THE LOCATION OF THE
     !     SPLIT IS KNOWN; THEN: SET THE SPLIT POINT AND BRANCH. ELSE: SET
     !     SPLIT POINT TO THE MEDIAN.

     if (LEN.le.2) then
        LEN = 1
        PRANG = 0.
     else
        X = XSMAL+(XRANG/2.)
        PRANG = XRANG/FLOAT(LEN-1)
        LN = LEN
        LEN = (LEN+1)/2
     end if

     !     MAKE SURE THAT THE LOCATION OF THE SPLIT IS AWAY FROM A VERY
     !     SMALL CLASS BOUNDRY.  THIS IS DONE BY LOOKING "DOWN" THE LIST
     !     OF ENTRIES TO INSURE THAT A VERY SMALL CLASS BOUNDRY IS NOT
     !     USED.  WE COULD ALSO LOOK "UP"...BUT WE ARE NOT GOING TO FOR NOW.

     !     JK IS THE NUMBER OF POSSIBLE SPLIT LOCATION "BELOW" THE ONE
     !     FOUND ABOVE. (WK3 & WK4 ARE INDEXED IN DESCENDING ORDER).

     JK = IND2(IREC)-LEN-1
     if (JK.ge.1) then
        do J = 1,JK
           I = IND1(IREC)-LEN
           if (LTWO) then
              if (WK4(IND(I))-WK4(IND(I+1)).gt. .001 ) goto 170
           else
              if (WK3(IND(I))-WK3(IND(I+1)).gt. .001 ) goto 170
           end if
           LEN = LEN+1
           165 continue
        end do
        170 continue
     end if

     if (LDEBG) write (JOSTND,162) XRANG,PRANG,LN,LEN,I1,I2
     162 format (' IN COMPRS: NEW WAY: XRANG,PRANG,LN,LEN,I1,I2=', &
          & 2E15.7,4I5)

     !     PERFORM THE SPLIT. INCREMENT THE CLASS COUNTER AND SPLIT CLASS
     !     IREC, ASSIGN THE SPLIT TO CLASS NCLS1. UPDATE THE LIST OF CLASS
     !     RANGES STORED IN WK6 AND WK5. (I POINTS TO THE LAST MEMBER OF THE
     !     UPPER CLASS.

     NCLS1 = NCLS1+1
     IND1(NCLS1) = IND1(IREC)
     I = IND1(IREC)-LEN
     IND1(IREC) = I
     IND2(NCLS1) = LEN
     IND2(IREC) = IND2(IREC)-LEN
     JK = IND(I1)

     !     IF THE SPLIT IS BASED ON THE FIRST SCORE; THEN:

     if (.not.LTWO) then

        !         (A) UPDATE THE CLASS RANGE VECTOR BY COMPUTING THE
        !             RANGES USING THE POINTERS (REMEMBER, THE LIST IS SORTED).
        !         (B) UPDATE THE CLASS RANGE VECTOR FOR THE SECOND BY SEARCHING
        !             FOR MAX AND MIN WITHIN EACH CLASS AND COMPUTE THE RANGES.

        J = IND(I+1)
        WK6(NCLS1) = WK3(J)-XSMAL
        J = IND(I)
        WK6(IREC) = WK3(JK)-WK3(J)
        LEN = IND2(IREC)
        WK5(IREC) = CMRANG(LEN,IND(I1),WK4)
        LEN = IND2(NCLS1)
        WK5(NCLS1) = CMRANG(LEN,IND(I+1),WK4)
     else

        !        ELSE (THE SPLIT IS BASED ON THE SECOND SCORE):

        !        (A) UPDATE THE CLASS RANGE VECTOR FOR THE SECOND BY COMPUTING
        !            THEN RANGE (THE SORT IS ON THE SECOND SCORE).
        !        (B) RESORT THE POINTERS ON THE FIRST SCORE -- SORT EACH NEW
        !            CLASS SEPERATELY.
        !        (C) UPDATE THE CLASS RANGE VECTOR FOR THE FIRST BY COMPUTING
        !            THE RANGE.

        J = IND(I+1)
        WK5(NCLS1) = WK4(J)-XSMAL
        J = IND(I)
        WK5(IREC) = WK4(JK)-WK4(J)
        LEN = IND2(IREC)
        call RDPSRT (LEN,WK3,IND(I1),.false.)
        LEN = IND2(NCLS1)
        call RDPSRT (LEN,WK3,IND(I+1),.false.)
        JK = IND(I1)
        J = IND(I)
        WK6(IREC) = WK3(JK)-WK3(J)
        J = IND(I2)
        JK = IND(I+1)
        WK6(NCLS1) = WK3(JK)-WK3(J)
     end if
     190 continue
  end do
  195 continue
  NCLAS = NCLS1

  !     (E) RESORT THE CLASS POINTERS

  call IQRSRT(IND1,NCLAS)
  200 continue

  !     WRITE DEBUG IF REQUESTED (LDEBG=.TRUE.)

  if (.not.LDEBG) goto 209
  write (JOSTND,201)
  201 format (//' CLASS TREE#   SCORES',7X,'PROB',8x,'  MORT(WK2) IMC ', &
       & '   ISP ICR ITRUNC NORMHT  DBH HT    PCT   DG   CFV ', &
       & '       HT2TDBF HT2TDCF   ITRE')
  I1 = 1
  TSSWC = 0.
  do I = 1,NCLAS
     SSWC = 0.
     I2 = IND1(I)
     JK = I2-I1+1
     J = IND(I1)
     K = IND(I2)
     X1 = WK3(J)-WK3(K)
     X2 = CMRANG(JK,IND(I1),WK4)
     !*    WRITE (JOSTND,202) I,X1,X2,JK
     !*202 FORMAT (/1X,I4,'; FIRST SCORE RANGE=',F15.4,'; SECOND RANGE=',
     !*   >       F15.4,'; NUMBER OF RECORDS=',I4)

     !     FIND THE WITHIN CLASS MEAN

     XBAR = 0.
     do ICL = I1,I2
        K = IND(ICL)
        XBAR = XBAR+WK3(K)
        203 continue
     end do
     DIV = I2-I1+1
     XBAR = XBAR/DIV

     !     CALCULATE THE WITHIN CLASS SUM OF SQUARES

     do ICL = I1,I2
        K = IND(ICL)
        if (I2-I1.gt.0) SSWC = SSWC+ (WK3(K)-XBAR)**2
        if (LDEBG) write (JOSTND,204) K,WK3(K),WK4(K),PROB(K),WK2(K), &
             & IMC(K),ISP(K),ICR(K),ITRUNC(K),NORMHT(K),DBH(K),HT(K), &
             & PCT(K),DG(K),CFV(K),HT2TD(K,2),HT2TD(K,1),ITRE(K)
        204 format (T8,I4,2E15.7,1X,F7.3,F9.5,I3,2I4,2I7,2(1X,F6.2),1X, &
             & F5.1,1X,F5.2,1X,F8.2,1X,F8.2,1X,F8.2,I6)
        205 continue
     end do
     TSSWC = TSSWC+SSWC
     I1 = I2+1
     !*    WRITE(JOSTND,206)SSWC
     !*206 FORMAT(' CORRECTED SUM OF SQUARES WITHIN THIS CLASS=',E15.6)
     207 continue
  end do
  write (JOSTND,208) TSSWC
  208 format ( /' TOTAL WITHIN CLASS SUM OF SQUARES=',E15.6)
  209 continue

  !     STEP7:  DO THE AVERAGEING OF ALL THE TREES IN EACH CLASS
  !     AND MOVE THE AVERAGE TREE INTO THE FIRST-TREES'S POSITION
  !     IN THE TREE ATTRIBUTE VECTOR (ARRAYS).  FIND THE MODE OF THE
  !     DISTRIBUTION OF NOMINAL VARIABLES AND MOVE THE MODE FOR EACH
  !     CLASS TO THE FIRST-TREES'S POSITION IN THE TREE ATTRIBUTE VECTOR.

  !     NOV 1995: CHANGED THE USE OF PROB TO PROB+WK2...AND STORED THIS
  !     SUM IN WK5.

  !     THERE ARE TWO SPECIAL CASSES (CODE ADDED IN MARCH 1981):
  !     1.  TRUNCATED TREES, AND
  !     2.  THE COMPRESSION OF POINTS, ALSO KNOWN AS SUBPOLTS.

  !     TO COMPRESS A CLASS WHICH INCLUDES ONE OR MORE TRUNCATED
  !     TREES:
  !     A.  SUM THE PROB+WK2 FOR THE CLASS. CALL A RANDOM NUMBER BETWEEN
  !     ZERO AND THE SUM OF THE PROB+WK2.
  !     B.  PRODUCE A CUMULATIVE ARRAY OF PROB+WK2 (STORED IN WK3). IF
  !     THE RANDOM NUMBER IS LESS THAN OR EQUAL TO A CUMULATIVE VALUE,
  !     THEN THE "TRUNCATED" OR "UNTRUNCATED" STATUS OF THE TREE IS
  !     USED FOR THE CLASS (SAMPLING PROPORTIONAL TO SIZE).
  !     C.  IF THE TREE CLASS IS NOT "TRUNCATED", THEN:  USE THE VALUE
  !     HT FROM NON-TURNCATED TREES AND NORMHT FOR TRUNCATED TREES
  !     IN COMPUTING THE AVERAGE HEIGHT. THEN SET NORMHT AND ITRUNC
  !     EQUAL TO ZERO.  OTHERWISE, THE TREE CLASS IS TRUNCATED,
  !     SO FOR THE VALUE OF HT SIMPLY AVERAGE THE VALUES OF HT FROM
  !     ALL OF THE TREES IN THE CLASS.  FOR NORMHT, USE THE VALUE
  !     OF NORMHT FOR TRUNCATED TREES AND HT FOR NONTRUNCATED TREES.
  !     FOR ITRUNC, WE MUST FIRST "TRUNCATE" THE NONTRUNCATED TREES.
  !     THE POINT OF TRUNCATION IS PROPORTIONALLY THE SAME AS THE
  !     AVERAGE PROPORTION OF TRUNCATION ON THE TRUNCATED TREES.
  !     THEN THE AVERAGE VALUES OF ITRUNC FOR ALL OF THE TREES IN THE
  !     CLASS ARE USED TO COMPUTE THE VALUE OF ITRUNC FOR THE CLASS.

  !     COMPRESSION OF POINTS (SUBPLOTS) IS DONE BY FOLLOWING STEPS
  !     A & B, ABOVE EXCEPT THAT THE POINT CORRESPONDING TO THE TREE
  !     RECORD SELECTED BECOMES THE POINT FOR THE CLASS.

  !     MAKE SURE THAT THE TARGET TREE RECORD IS ALWAYS THE ONE
  !     THAT IS CLOSEST TO THE TOP OF THE LIST, IE THE MIN.

  I1 = 1
  do ICL = 1,NCLAS
     I2 = IND1(ICL)
     if (I1.lt.I2) then
        do II = I1+1,I2
           if (IND(I1).gt.IND(II)) then
              I = IND(I1)
              IND(I1) = IND(II)
              IND(II) = I
           end if
           210 continue
        end do
     end if
     I1 = I2+1
     211 continue
  end do

  !     CREATE THE SUM OF PROB+WK2, STORE IN WK5.

  do I = 1,ITRN
     WK5(I) = PROB(I)+WK2(I)
     212 continue
  end do

  !     CALL THE WESTERN ROOT DISEASE VER. 3.0 SUBROUTINE TO COMPRESS
  !     ROOT DISEASE TREE LISTS.

  call RDCMPR (NCLAS,WK5,IND,IND1)

  !     CALL THE BLISTER RUST MODEL SUBROUTINE TO COMPRESS
  !     BLISTER RUST TREE ATTRIBUTES.

  call BRCMPR (NCLAS,WK5,IND,IND1)

  !     CALL THE FIRE/SNAG MODEL SUBROUTINE TO COMPRESS THE
  !     FIRE/SNAG ATTRIBUTES.

  call FMCMPR (NCLAS)

  !     CALL VISULIZATION COMPRESSION INITIALIZATION

  call SVCMP1

  TTPRB = 0.
  TTWK2 = 0.
  I1 = 1
  do ICL = 1,NCLAS

     !       SET THE POINTERS TO THE TREES IN THE CLASS

     I2 = IND1(ICL)
     IREC1 = IND(I1)

     !     IF THERE IS ONLY ONE RECORD IN CLASS ICL, THEN: SKIP THE CLASS

     if (I1 .eq. I2) goto 480

     !     CREATE A COMULATIVE PROB+WK2 FOR ALL THE TREES IN THE CLASS.

     XP = WK5(IREC1)
     TXP = XP
     WK3(IREC1) = XP
     K = I1+1
     do I = K,I2
        IREC = IND(I)
        XP = WK5(IREC)
        TXP = TXP+XP
        WK3(IREC) = TXP
        213 continue
     end do

     !     ALL OF THE PROB+WK2 IS ZERO (THIS SHOULD NEVER HAPPEN), BRANCH
     !     TO STMT 480 TO SKIP PROCESSING THE TREE RECORD.

     if (TXP.eq.0.0) goto 480

     !     CALL A RANDOM NUMBER WHICH WILL BE USED TO SELECT THE
     !     TRUNCATED STATUS, PLOT LOCATION, SPECIES, MANAGEMENT CODE,
     !     CUT CODE STATUS OF THE CLASS, SPECIAL TREE STATUS,
     !     AND DETERMINE VALUE OF IESTAT.

     call RANN(X)
     X = X*TXP
     do I = I1,I2
        IREC = IND(I)
        if (X.le.WK3(IREC)) goto 217
        216 continue
     end do
     217 continue
     LTRNK = NORMHT(IREC).gt.0
     ITRE(IREC1) = ITRE(IREC)
     ISP(IREC1) = ISP(IREC)
     KUTKOD(IREC1) = KUTKOD(IREC)
     ISPECL(IREC1) = ISPECL(IREC)
     IMC(IREC1) = IMC(IREC)
     IESTAT(IREC1) = IESTAT(IREC)
     IDTREE(IREC1) = IDCMP2+IY(MAX(1,ICYC))
     NCFDEF(IREC1) = NCFDEF(IREC)
     NBFDEF(IREC1) = NBFDEF(IREC)

     !     POST THE COMPRESS TO THE VISULIZATION

     call SVCMP2(IREC1,IREC)

     !     GET DWARF MISTLETOE RATING FOR IREC AND PUT IT INTO IREC1.

     call MISGET(IREC,IDMR)
     call MISPUT(IREC1,IDMR)

     !     COMPUTE THE AVERAGE HT, NORMHT, AND ITRUNC FOR THE TREE CLASS.
     !     IF THE TREE CLASS IS NOT A "TRUNCATED" CLASS (LTRNK=FALSE),
     !     SIMPLY AVERAGE THE HEIGHT.

     if (LTRNK) goto 221
     HTI = HT(IREC1)
     if (NORMHT(IREC1) .gt. 0)HTI = NORMHT(IREC1)/100.
     HTI = HTI*WK5(IREC1)
     NORMHT(IREC1) = 0
     ITRUNC(IREC1) = 0
     do I = K,I2
        IREC = IND(I)
        X = HT(IREC)
        if (NORMHT(IREC).gt.0) X = NORMHT(IREC)/100.
        HTI = HTI+X*WK5(IREC)
        220 continue
     end do
     HT(IREC1) = HTI/WK3(IREC)
     goto 226
     221 continue

     !     THE TREE CLASS IS A "TRUNCATED" CLASS.  COMPUTE THE AVERAGE
     !     PROPORTION OF TRUNCATION.

     X = 0.
     XP = 0.
     do I = I1,I2
        IREC = IND(I)
        if (NORMHT(IREC).le.0) goto 222
        X = X+ITRUNC(IREC)/100.*WK5(IREC)
        XP = XP+HT(IREC)*WK5(IREC)
        222 continue
     end do
     X = X/XP

     !     NOW, COMPUTE THE AVERAGE HT,ITRUNC,NORMHT FOR THE "TRUNCATED"
     !     TREE CLASS.

     XIT = 0.
     XNR = 0.
     HTI = 0.
     do I = I1,I2
        IREC = IND(I)
        XP = WK5(IREC)
        HTI = HTI+HT(IREC)*XP
        if (NORMHT(IREC).gt.0) then
           XNR = XNR+NORMHT(IREC)/100.*XP
           XIT = XIT+ITRUNC(IREC)/100.*XP
        else
           XNR = XNR+HT(IREC)*XP
           XIT = XIT+HT(IREC)*X*XP
        end if
        225 continue
     end do
     TXP = WK3(IREC)
     HT(IREC1) = HTI/TXP
     NORMHT(IREC1) = IFIX(XNR/TXP*100.)
     ITRUNC(IREC1) = IFIX(XIT/TXP*100.)
     226 continue

     !     LOAD THE SCALARS AND INITIALIZE THE VARIABLES
     !     NECESSARY TO FIND THE AVERAGE F0R THE CONTINOUS VARIABLES.

     XP = WK5   (IREC1)
     BFVI = BFV   (IREC1) * XP
     CFVI = CFV   (IREC1) * XP
     MCFVI = MCFV  (IREC1) * XP
     SCFVI = SCFV  (IREC1) * XP

     CULLI = CULL   (IREC1) * XP
     DECAYI = INT(DECAYCD(IREC1) * XP)
     WDLDSTEMI = INT(WDLDSTEM(IREC1) * XP)

     !     CARBON AND BIOMASS ARRAYS
     ABVGRD_BIOI = ABVGRD_BIO (IREC1) * XP
     MERCH_BIOI = MERCH_BIO   (IREC1) * XP
     CUBSAW_BIOI = CUBSAW_BIO (IREC1) * XP
     FOLI_BIOI = FOLI_BIO     (IREC1) * XP
     ABVGRD_CARBI = ABVGRD_CARB (IREC1) * XP
     MERCH_CARBI = MERCH_CARB  (IREC1) * XP
     CUBSAW_CARBI = CUBSAW_CARB (IREC1) * XP
     FOLI_CARBI = FOLI_CARB   (IREC1) * XP
     CARB_FRACI = CARB_FRAC   (IREC1) * XP

     HT2TDBFI = HT2TD(IREC1,1)* XP
     HT2TDCFI = HT2TD(IREC1,2)* XP
     DBHI = DBH   (IREC1)
     DBHI = DBHI*DBHI     * XP
     DGI = DG    (IREC1) * XP
     HTGI = HTG   (IREC1) * XP
     OLDPTI = OLDPCT(IREC1) * XP
     PCTI = PCT   (IREC1) * XP
     WK1I = WK1   (IREC1) * XP
     WK2I = WK2   (IREC1)
     PROBI = PROB  (IREC1)
     PCFVI = PTOCFV(IREC1) * XP
     PMCVI = PMRCFV(IREC1) * XP
     PSCVI = PSCFV (IREC1) * XP
     PMBVI = PMRBFV(IREC1) * XP
     PDBHI = PDBH(IREC1) * XP
     PHTI = PHT(IREC1) * XP
     IF (LDEBG) WRITE (JOSTND,'('' IREC1='',I4,'' PROB='',F7.3,      &
          &                           '' PROBI='',F7.3)') &
          & IREC1,PROB(IREC1),PROBI
     XICRI = ICR   (IREC1) * XP
     DF11 = FLOAT(DEFECT(IREC1)/1000000) * XP
     DF22 = FLOAT((DEFECT(IREC1)/10000) - &
          & (DEFECT(IREC1)/1000000)*100)*XP
     DF33 = FLOAT((DEFECT(IREC1)/100) - (DEFECT(IREC1)/10000)*100)*XP
     DF44 = FLOAT(DEFECT(IREC1) - (DEFECT(IREC1)/100)*100)*XP
     CRWDI = CRWDTH(IREC1) * XP

     !     ADD IN THE OTHER TREES WHICH FORM THE CLASS.

     I1 = I1+1
     do I = I1,I2
        IREC = IND(I)

        !     SET THE SIGN NEGATIVE FOR INDICES TO VACANT POSITIONS.

        IND(I) = -IND(I)
        XP = WK5(IREC)

        BFVI = BFVI   + BFV   (IREC) * XP
        CFVI = CFVI   + CFV   (IREC) * XP
        MCFVI = MCFVI  + MCFV  (IREC) * XP
        SCFVI = SCFVI  + SCFV  (IREC) * XP

        CULLI = CULLI         + CULL    (IREC) * XP
        DECAYI = INT(DECAYI       + DECAYCD (IREC) * XP)
        WDLDSTEMI = INT(WDLDSTEMI + WDLDSTEM(IREC) * XP)

        !     CARBON AND BIOMASS ARRAYS
        ABVGRD_BIOI = ABVGRD_BIOI +  ABVGRD_BIO (IREC) * XP
        MERCH_BIOI = MERCH_BIOI +   MERCH_BIO (IREC) * XP
        CUBSAW_BIOI = CUBSAW_BIOI +  CUBSAW_BIO (IREC) * XP
        FOLI_BIOI = FOLI_BIOI +    FOLI_BIO (IREC) * XP
        ABVGRD_CARBI = ABVGRD_CARBI + ABVGRD_CARB (IREC) * XP
        MERCH_CARBI = MERCH_CARBI +  MERCH_CARB (IREC) * XP
        CUBSAW_CARBI = CUBSAW_CARBI + CUBSAW_CARB (IREC) * XP
        FOLI_CARBI = FOLI_CARBI +   FOLI_CARB (IREC) * XP
        CARB_FRACI = CARB_FRACI +   CARB_FRAC (IREC) * XP

        HT2TDBFI = HT2TDBFI+HT2TD(IREC,1)* XP
        HT2TDCFI = HT2TDCFI+HT2TD(IREC,2)* XP
        X = DBH(IREC)
        DBHI = DBHI   + X*X          * XP
        DGI = DGI    + DG    (IREC) * XP
        HTGI = HTGI   + HTG   (IREC) * XP
        OLDPTI = OLDPTI + OLDPCT(IREC) * XP
        PCTI = PCTI   + PCT   (IREC) * XP
        WK1I = WK1I   + WK1   (IREC) * XP
        WK2I = WK2I   + WK2   (IREC)
        PROBI = PROBI  + PROB  (IREC)
        PCFVI = PCFVI  + PTOCFV(IREC) * XP
        PMCVI = PMCVI  + PMRCFV(IREC) * XP
        PSCVI = PSCVI  + PSCFV (IREC) * XP
        PMBVI = PMBVI  + PMRBFV(IREC) * XP
        PDBHI = PDBHI  +   PDBH(IREC) * XP
        PHTI = PHTI   +    PHT(IREC) * XP
        IF (LDEBG) WRITE (JOSTND,'('' IREC ='',I4,'' PROB='',F7.3,    &
             &                           '' PROBI='',F7.3)') &
             & IREC,PROB(IREC),PROBI
        XICRI = XICRI  + ICR   (IREC) * XP
        DF11 = DF11 +FLOAT(DEFECT(IREC)/1000000) * XP
        DF22 = DF22 +FLOAT((DEFECT(IREC)/10000) - &
             & (DEFECT(IREC)/1000000)*100)*XP
        DF33 = DF33 +FLOAT((DEFECT(IREC)/100) - &
             & (DEFECT(IREC)/10000)*100)*XP
        DF44 = DF44 +FLOAT(DEFECT(IREC) - (DEFECT(IREC)/100)*100)*XP
        CRWDI = CRWDI + CRWDTH(IREC) * XP

        !     POST THE COMPRESS TO THE VISULIZATION

        call SVCMP2(IREC1,IREC)
        300 continue
     end do

     !     DIVIDE BY THE TOTAL PROB+WK2 AND MOVE THE VALUES INTO
     !     THE 'IREC1' POSITION IN THE ARRAYS.

     TXP = WK3(IREC)
     BFV(IREC1) = BFVI / TXP
     CFV(IREC1) = CFVI / TXP
     MCFV(IREC1) = MCFVI / TXP
     SCFV(IREC1) = SCFVI / TXP

     CULL(IREC1) = CULLI / TXP
     DECAYCD(IREC1) = INT(DECAYI / TXP)
     WDLDSTEM(IREC1) = INT(WDLDSTEMI / TXP)

     !     CARBON AND BIOMASS ARRAYS
     ABVGRD_BIO  (IREC1) = ABVGRD_BIOI / TXP
     MERCH_BIO   (IREC1) = MERCH_BIOI / TXP
     CUBSAW_BIO  (IREC1) = CUBSAW_BIOI / TXP
     FOLI_BIO    (IREC1) = FOLI_BIOI / TXP
     ABVGRD_CARB (IREC1) = ABVGRD_CARBI / TXP
     MERCH_CARB  (IREC1) = MERCH_CARBI / TXP
     CUBSAW_CARB (IREC1) = CUBSAW_CARBI / TXP
     FOLI_CARB   (IREC1) = FOLI_CARBI / TXP
     CARB_FRAC   (IREC1) = CARB_FRACI / TXP

     HT2TD(IREC1,1) = HT2TDBFI / TXP
     HT2TD(IREC1,2) = HT2TDCFI / TXP
     DBH(IREC1) = SQRT(DBHI/TXP)
     DG(IREC1) = DGI / TXP
     HTG(IREC1) = HTGI / TXP
     OLDPCT(IREC1) = OLDPTI / TXP
     PCT(IREC1) = PCTI / TXP
     WK1(IREC1) = WK1I / TXP
     WK2(IREC1) = WK2I
     ICR(IREC1) = NINT(XICRI / TXP)
     PROB(IREC1) = PROBI
     IDF11 = IFIX(DF11 / TXP + .5)
     IDF22 = IFIX(DF22 / TXP + .5)
     IDF33 = IFIX(DF33 / TXP + .5)
     IDF44 = IFIX(DF44 / TXP + .5)
     DEFECT(IREC1) = IDF11*1000000 + IDF22*10000 + IDF33*100 + IDF44
     PTOCFV(IREC1) = PCFVI / TXP
     PMRCFV(IREC1) = PMCVI / TXP
     PSCFV (IREC1) = PSCVI / TXP
     PMRBFV(IREC1) = PMBVI / TXP
     PDBH  (IREC1) = PDBHI / TXP
     PHT   (IREC1) = PHTI  / TXP
     CRWDTH(IREC1) = CRWDI / TXP
     ZRAND(IREC1) = -999.0 ! reset the serial correlation

     !     END OF COMPRESSION LOOP

     480 continue

     !     PRINT DEBUG OUTPUT, IF DESIRED.

     if (LDEBG) then
        TTPRB = TTPRB+PROB(IREC1)
        TTWK2 = TTWK2+WK2(IREC1)
        write (JOSTND,485) ICL,IREC1,PROB(IREC1),WK2(IREC1), &
             & IMC(IREC1),ISP(IREC1),ICR(IREC1),ITRUNC(IREC1),NORMHT(IREC1), &
             & DBH(IREC1),HT(IREC1),PCT(IREC1),DG(IREC1),CFV(IREC1), &
             & HT2TD(IREC1,2),HT2TD(IREC1,1),ITRE(IREC1)
        485 format (1X,I6,I4,T43,F7.3,F9.5,I3,2I4,2I7,2(1X,F6.2),1X,F5.1, &
             & 1X,F5.2,1X,F8.2,1X,F8.2,F8.2,I3)
     end if

     !     REDEFINE I1 SUCH THAT IT POINTS TO THE FIRST
     !     INDEX IN THE NEXT CLASS.

     I1 = I2+1
     500 continue
  end do
  IF (LDEBG) WRITE (JOSTND,'('' SUM OF PROB (AFTER)= '',F10.4,      &
       &                           '' SUM OF MORT= '',F10.4)') TTPRB,TTWK2

  !     RE-REFERENCE THE POINTERS IN THE VISULIZATION DATA

  call SVCMP3

  !     STEP8:  MOVE THE TREES IN THE BOTTOM OF THE ATTRIBUTE VECTORS
  !     TO THE UPPER-MOST VACANT POSITIONS.

  call TREDEL (ITRN-NCLAS,IND)

  return
end subroutine COMPRS
