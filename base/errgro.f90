  5711 format('FVS47 WARNING: A DEPRECATED BOARD-FOOT VOLUME ', &
       & 'COMPUTATION METHOD HAS BEEN REQUESTED.  ', &
       & 'METHOD CODE 6 (NATIONAL VOLUME ESTIMATOR LIBRARY) WILL BE ', &
