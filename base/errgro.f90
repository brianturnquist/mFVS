  5911 format('FVS49 WARNING: VOLUME KEYWORD HAS BEEN RECOGNIZED ', &
       & 'BUT HAS BEEN DEACTIVATED BY A PREVIOUS CALL TO USE FIAVBC ', &
       & 'FOR COMPUTATION OF CUBIC FOOT VOLUMES')
