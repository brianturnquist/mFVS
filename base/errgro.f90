  5811 format('FVS48 WARNING: A DEPRECATED CUBIC FOOT VOLUME ', &
       & 'COMPUTATION METHOD HAS BEEN REQUESTED.  ', &
       & 'METHOD CODE 6 (NATIONAL VOLUME ESTIMATOR LIBRARY) WILL BE ', &
       & 'USED BY DEFAULT.' )
  if (ICCODE .lt. 2) ICCODE = 1
  go to 9000

  !                        ERROR NUMBER 49
  5900 continue
  write(JOSTND,5910)  PREF
  write(CMSG,  5911)

  5910 format(/A11,'FVS49 WARNING: VOLUME KEYWORD HAS BEEN RECOGNIZED '/, &
       & T12,'BUT HAS BEEN DEACTIVATED BY A PREVIOUS CALL TO USE FIAVBC ', &
