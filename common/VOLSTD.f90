character(len=11) :: VEQNNC(MAXSP)

integer :: IBTRAN(MAXSP),ICTRAN(MAXSP)

real    :: ALPHA

real    :: BFMIND(MAXSP),BFSTMP(MAXSP),BFTOPD(MAXSP),BFVEQL(7,MAXSP),BFVEQS(7,MAXSP),BTRAN(MAXSP),&
     &CFVEQL(7,MAXSP),CFVEQS(7,MAXSP),CTRAN(MAXSP),LOGDIA(21,3),LOGVOL(7,20),CFLDIA(21,3),CFLVOL(7,20),&
     &BFLDIA(21,3),BFLVOL(7,20)

