common /VOLSTD/ ALPHA,BFMIND,BFSTMP,BFTOPD,BFVEQL,BFVEQS,BTRAN,&
     &CFVEQL,CFVEQS,CTRAN,IBTRAN,ICTRAN,LOGDIA,LOGVOL,&
     &LSTATS,CFLDIA,CFLVOL,BFLDIA,BFLVOL

!  VARIABLE DEFINITIONS:

!     ALPHA --
!    BFLDIA -- LOG-END DIAMETERS OF THE CURRENT TREE'S BOARD FOOT LOGS,
!              AS PRICED BY ECON; SAME LAYOUT AS LOGDIA. SET BY NATCRS;
!              ZEROED FOR EACH TREE IN VOLS.
!    BFLVOL -- VOLUMES OF THE CURRENT TREE'S BOARD FOOT LOGS, AS PRICED
!              BY ECON; SAME LAYOUT AS LOGVOL. SET BY NATCRS; ZEROED
!              FOR EACH TREE IN VOLS.
!    BFMIND -- MINIMUM DIAMETER BREAST HEIGHT (DBH) FOR BOARD FOOT
!              MERCHANTABILITY
!    BFSTMP -- CARRIES STUMP HEIGHTS FOR MERCHANTABLE BOARD FOOT VOLUME
!              EQUATIONS BY SPECIES. CAN BE RESET BY KEYWORD.
!    BFTOPD -- CARRIES TOP DIAMETERS FOR MERCHANTABLE BOARD FOOT VOLUME
!              EQUATIONS BY SPECIES. CAN BE RESET BY KEYWORD.
!    BFVEQL --
!    BFVEQS --
!     BTRAN --
!    CFLDIA -- LOG-END DIAMETERS OF THE CURRENT TREE'S CUBIC FOOT LOGS,
!              AS PRICED BY ECON; SAME LAYOUT AS LOGDIA. SET BY NATCRS;
!              ZEROED FOR EACH TREE IN VOLS.
!    CFLVOL -- VOLUMES OF THE CURRENT TREE'S CUBIC FOOT LOGS, AS PRICED
!              BY ECON; SAME LAYOUT AS LOGVOL. SET BY NATCRS; ZEROED
!              FOR EACH TREE IN VOLS.
!    CFVEQL --
!    CFVEQS --
!     CTRAN --
!    IBTRAN --
!    ICTRAN --
!    LOGDIA -- LOG-END DIAMETERS FOR UP TO 20 LOGS PER TREE: ( ,1)
!              SCALING DIA. INSIDE BARK,( ,2) ACTUAL PREDICTED DIA.
!              INSIDE BARK ( ,3) ACTUAL PREDICTED DIA. OUTSIDE BARK.
!              DIAMETERS ARE FROM LARGE TO SMALL. FIRST DIA. IS LARGE
!              DIA. OF BUTT END, SECOND DIA. IS SMALL END OF BUTT = LARGE
!              END OF SECOND LOG AND SO ON. HOLDS THE LOGS FROM THE LAST
!              VOLINITNVB CALL IN NATCRS; WORKING ARRAY ONLY. USE
!              CFLDIA OR BFLDIA FOR A TREE'S LOGS.
!    LOGVOL -- VOLUME OF UP TO 20 LOGS PER TREE: (1, ) GROSS SCRIBNER BF
!              (2, ) GROSS REMOVED SCRIBNER BF, (3, ) NET SCRIBNER BF
!              (4, ) GROSS CU, (5, ) GROSS REMOVED CU, (6, ) NET CU
!              (7, ) GROSS INTERNATIONAL 1/4 BF. HOLDS THE LOGS FROM THE
!              LAST VOLINITNVB CALL IN NATCRS; WORKING ARRAY ONLY.
!              USE CFLVOL OR BFLVOL FOR A TREE'S LOGS.
!    LSTATS --
!    VEQNNB -- NATIONAL CRUISE SYSTEM BOARD FOOT VOLUME EQUATION NUMBER
!              ENTERED WITH VOLEQNUM KEYWORD.
!    VEQNNC -- NATIONAL CRUISE SYSTEM CUBIC FOOT VOLUME EQUATION NUMBER
!              ENTERED WITH VOLEQNUM KEYWORD.
