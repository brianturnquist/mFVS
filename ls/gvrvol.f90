!=================!
!   ls : gvrvol   !
!=================!
! LS $Id$

subroutine GVRVOL (VN,VM,BBFV,ISPC,D,H,TKILL,BARK,ITRNC,VMAX,&
     &CTKFLG,BTKFLG,IT)
  implicit none

  !  GEVORKIANTZ VOLUME CALCULATION METHOD (METHC AND/OR METHB=5)
  !  THIS METHOD WAS SUPERCEEDED BY THE CLARK METHOD FALL 2009

  ! Common blocks
  include 'PRGPRM.f90'
  include 'CONTRL.f90'
  include 'VOLSTD.f90'
  include 'PLOT.f90'
  include 'ARRAYS.f90'

  ! Variables
  real    :: VOL(15)
  logical :: TKILL,CTKFLG,BTKFLG,DEBUG,DONE
  character(len=1) :: CTYPE
  character(len=1) :: HTTYP
  character(len=2) :: FORST
  character(len=2) :: PROD
  integer :: FOREST,IHT1,IHT2
  integer :: I1,I0,I02,I01,I,ISPC,IERR,IT,ITRNC
  real    :: SAWBF,SAWCU,X01,TOTCU,BOLT1,BOLT2,BFTDOB
  real    :: TOPDOB,SINDX,VM,VN,BBFV,H,D,BARK,VMAX
  integer :: IDANUW
  logical :: LDANUW

  !  DUMMY ARGUMENT NOT USED WARNING SUPPRESSION SECTION

  IDANUW = IT
  IDANUW = ITRNC
  LDANUW = BTKFLG
  LDANUW = CTKFLG
  LDANUW = TKILL

  !  CHECK FOR DEBUG

  call DBCHK(DEBUG,'VARVOL',6,ICYC)
  if (DEBUG)write(JOSTND,*)'IN GVRVOL -, ICYC= ',ICYC

  !  INITIALIZE VOLUME ARRAY TO ZERO

  do I = 1,15
     VOL(I) = 0.
     11 continue
  end do
  FOREST = KODFOR-900
  write(FORST,'(I2)')FOREST
  if (FOREST.lt.10)FORST(1:1) = '0'
  SINDX = SITEAR(ISPC)
  DONE = .false.
  TOPDOB = TOPD(ISPC)/BARK
  BFTDOB = BFTOPD(ISPC)/BARK

  if (DEBUG)write(JOSTND,*)&
       &' TOPDOB= ',TOPDOB,' BFTDOB=',BFTDOB,' BRATIO=',BARK

  !  CALL NBOLT TO COMPUTE THE TOTAL NUMBER OF 8' BOLTS TO A SPECIFIED
  !  PULPWOOD AND SAWTIMBER TOP DIAMETER.
  !    IHT1 = # OF SAWLOG 8' BOLTS
  !    IHT2 = # OF PULPWOOD 8' BOLTS

  call NBOLT(ISPC,H,D,DBHMIN,BFMIND,SINDX,TOPDOB,BFTDOB,&
       &JOSTND,DEBUG,IHT1,IHT2)
  BOLT1 = FLOAT(IHT1)
  BOLT2 = FLOAT(IHT2)
  if (DEBUG)write(JOSTND,*)' AFTER NBOLT BOLT1,BOLT2= ',BOLT1,BOLT2

  !  COMPUTE TOTAL MERCH CUBIC, SAWLOG CUBIC, AND SAWLOG BOARDFOOT VOLUME

  !  CASES 1-3 ASSUME THE MINIMUM SAWTIMBER DBH IS GREATER THAN THE
  !  MINIMUM PULPWOOD DBH

  if (DEBUG)write(JOSTND,*)' ISPC,D,DBHMIN,BFMIND,IHT1,IHT2= ',&
       &ISPC,D,DBHMIN(ISPC),BFMIND(ISPC),IHT1,IHT2

  !  SET CONSTANT ARGUMENTS IN CALL TO R9VOL

  !  REAL CONSTANT ARGUMENTS

  X01 = 0.

  !  INTEGER CONSTANT ARGUMENTS

  IERR = 0
  I01 = 0
  I02 = 0
  I0 = 0
  I1 = 1

  !  CHARACTER CONSTANT ARGUMENTS

  CTYPE = 'F'
  HTTYP = 'L'

  !  TREE DBH IS LESS THAN PULPWOOD MIN DBH, OR NO PULPWOOD HT

  if (D.lt.DBHMIN(ISPC) .or. IHT2.le.0) then

     !  CASE 1: TREE DOES NOT MEET PULPWOOD SPECS

     TOTCU = 0.

     !  TREE DBH IS >PULPWOOD MIN DBH BUT <SAWTIMBER MIN DBH, OR NO SAW HT

  else if (D.lt.BFMIND(ISPC).or. IHT1.le.0) then

     !  CASE 2: TREE ONLY HAS PULPWOOD (PROD='02')

     if (DEBUG)write(JOSTND,*)' CASE 2 PWVOL VEQNNC,BOLT2,D,H,FORST= '&
          &,VEQNNC(ISPC),BOLT2,D,H,FOREST

     PROD = '02'
     call R9VOL(VEQNNC(ISPC),H,BOLT2,BOLT2,D,VOL,FORST,I01,&
          &I02,PROD,CTYPE,I1,I1,I0,I1,HTTYP,IERR)

     if (DEBUG)write(JOSTND,*)' AFTER CASE 2 PWVOL VOL= ',VOL

     TOTCU = VOL(4)
     SAWCU = 0.0
     SAWBF = 0.0
     DONE = .true.

     !  TREE DBH IS >SAWTIMBER MIN DBH, POSITIVE SAW HT AND PULP HT

  else

     !  CASE 3: TREE HAS SAWTIMBER AND PULPWOOD (PROD='01' AND TOPWOOD)

     if (DEBUG)write(JOSTND,*)' CASE 3 SBVOL VEQNNC,H,BOLT1,BOLT2,D,',&
          &'FORST= ',VEQNNC(ISPC),H,BOLT1,BOLT2,D,FORST

     PROD = '01'
     call R9VOL(VEQNNC(ISPC),H,BOLT1,BOLT2,D,VOL,FORST,I01,&
          &I02,PROD,CTYPE,I1,I1,I0,I1,HTTYP,IERR)
     SAWBF = VOL(2)
     SAWCU = VOL(4)
     TOTCU = SAWCU+VOL(7)
     if (DEBUG)write(JOSTND,*)' AFTER CASE 3 TCVOL VOL= ',VOL
     if (VEQNNB(ISPC).eq.VEQNNC(ISPC)) then
        DONE = .true.
     else
        call R9VOL(VEQNNB(ISPC),H,BOLT1,BOLT2,D,VOL,FORST,I01,&
             &I02,PROD,CTYPE,I1,I1,I0,I1,HTTYP,IERR)
        SAWBF = VOL(2)
        DONE = .true.
        if (DEBUG)write(JOSTND,*)' AFTER CASE 3 (CALL 2)TCVOL VOL= ',VOL
     end if
     if (DEBUG)write(JOSTND,*)' AFTER CASE 3 TCVOL VOL= ',VOL
  end if
  if (DONE)goto 51

  !--TREE DID NOT MEET PULPWOOD SPECS

  if (D .lt. BFMIND(ISPC)) then

     !  CASE 4: TREE DOES NOT MEET SAWTIMBER OR PULPWOOD SPECS

     SAWCU = 0.0
     SAWBF = 0.0
  else

     !  CASE 5: STRANGE CASE SPECS MET AND TREE ONLY HAS SAWTIMBER(PROD='01')

     if (DEBUG)write(JOSTND,*)' CASE 5 R9VOL VEQNNC,BOLT1,D,FORST= ',&
          &VEQNNC(ISPC),BOLT2,D,FOREST

     PROD = '01'
     call R9VOL(VEQNNC(ISPC),H,BOLT1,X01,D,VOL,FORST,I01,&
          &I02,PROD,CTYPE,I1,I1,I0,I0,HTTYP,IERR)

     if (DEBUG)write(JOSTND,*)' AFTER CASE 5 R9VOL VOL= ',VOL

     SAWCU = VOL(4)
     SAWBF = VOL(2)
     if (VEQNNB(ISPC).ne.VEQNNC(ISPC)) then
        call R9VOL(VEQNNB(ISPC),H,BOLT1,X01,D,VOL,FORST,I01,&
             &I02,PROD,CTYPE,I1,I1,I0,I0,HTTYP,IERR)
        SAWBF = VOL(2)
        if (DEBUG)write(JOSTND,*)' AFTER CASE 5 (CALL 2) R9VOL VOL= ',VOL
     end if
  end if

  !  SET RETURN VALUES.

  51 continue
  if (DEBUG)write(JOSTND,*)' TOTCU=',TOTCU,' SAWCU=',SAWCU,&
       &' SAWBF=',SAWBF
  VN = TOTCU
  VMAX = VN
  VM = SAWCU
  BBFV = SAWBF
  if (DEBUG)write(JOSTND,*)' RETURNING VN,VMAX,VM,BBFV= ',&
       &VN,VMAX,VM,BBFV

  return
end
