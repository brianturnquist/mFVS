!===============================================!
!   Compute tree age height and height growth   !
!===============================================!
! WS $Id$
subroutine HTCALC (IFOR,SINDX,ISPC,AG,HGUESS,JOSTND,DEBUG)
  implicit none

  ! THIS ROUTINE CALCULATES A POTENTIAL HT GIVEN AN SPECIES SITE AND AGE
  ! IT IS USED TO CALL POTHTG AND SITE

  ! Variables
  logical :: DEBUG
  integer :: JOSTND,ISPC,IFOR,INDX
  real    :: HGUESS,AG,SINDX,A,B,TERM,TERM2,B50
  real    :: DUNL1(6),DUNL2(6),DUNL3(6)
  integer :: IDANUW

  !  DATA STATEMENTS

  data DUNL1/ -88.9, -82.2, -78.3, -82.1, -56.0, -33.8 /
  data DUNL2/ 49.7067, 44.1147, 39.1441,&
       &35.4160, 26.7173, 18.6400 /
  data DUNL3/ 2.375, 2.025, 1.650, 1.225, 1.075, 0.875 /

  !     SPECIES LIST FOR WESTERN SIERRAS VARIANT.

  !     1 = SUGAR PINE (SP)                   PINUS LAMBERTIANA
  !     2 = DOUGLAS-FIR (DF)                  PSEUDOTSUGA MENZIESII
  !     3 = WHITE FIR (WF)                    ABIES CONCOLOR
  !     4 = GIANT SEQUOIA (GS)                SEQUOIADENDRON GIGANTEAUM
  !     5 = INCENSE CEDAR (IC)                LIBOCEDRUS DECURRENS
  !     6 = JEFFREY PINE (JP)                 PINUS JEFFREYI
  !     7 = CALIFORNIA RED FIR (RF)           ABIES MAGNIFICA
  !     8 = PONDEROSA PINE (PP)               PINUS PONDEROSA
  !     9 = LODGEPOLE PINE (LP)               PINUS CONTORTA
  !    10 = WHITEBARK PINE (WB)               PINUS ALBICAULIS
  !    11 = WESTERN WHITE PINE (WP)           PINUS MONTICOLA
  !    12 = SINGLELEAF PINYON (PM)            PINUS MONOPHYLLA
  !    13 = PACIFIC SILVER FIR (SF)           ABIES AMABILIS
  !    14 = KNOBCONE PINE (KP)                PINUS ATTENUATA
  !    15 = FOXTAIL PINE (FP)                 PINUS BALFOURIANA
  !    16 = COULTER PINE (CP)                 PINUS COULTERI
  !    17 = LIMBER PINE (LM)                  PINUS FLEXILIS
  !    18 = MONTEREY PINE (MP)                PINUS RADIATA
  !    19 = GRAY PINE (GP)                    PINUS SABINIANA
  !         (OR CALIFORNIA FOOTHILL PINE)
  !    20 = WASHOE PINE (WE)                  PINUS WASHOENSIS
  !    21 = GREAT BASIN BRISTLECONE PINE (GB) PINUS LONGAEVA
  !    22 = BIGCONE DOUGLAS-FIR (BD)          PSEUDOTSUGA MACROCARPA
  !    23 = REDWOOD (RW)                      SEQUOIA SEMPERVIRENS
  !    24 = MOUNTAIN HEMLOCK (MH)             TSUGA MERTENSIANA
  !    25 = WESTERN JUNIPER (WJ)              JUNIPERUS OCIDENTALIS
  !    26 = UTAH JUNIPER (UJ)                 JUNIPERUS OSTEOSPERMA
  !    27 = CALIFORNIA JUNIPER (CJ)           JUNIPERUS CALIFORNICA
  !    28 = CALIFORNIA LIVE OAK (LO)          QUERCUS AGRIFOLIA
  !    29 = CANYON LIVE OAK (CY)              QUERCUS CHRYSOLEPSIS
  !    30 = BLUE OAK (BL)                     QUERCUS DOUGLASII
  !    31 = CALIFORNIA BLACK OAK (BO)         QUERQUS KELLOGGII
  !    32 = VALLEY OAK (VO)                   QUERCUS LOBATA
  !         (OR CALIFORNIA WHITE OAK)
  !    33 = INTERIOR LIVE OAK (IO)            QUERCUS WISLIZENI
  !    34 = TANOAK (TO)                       LITHOCARPUS DENSIFLORUS
  !    35 = GIANT CHINQUAPIN (GC)             CHRYSOLEPIS CHRYSOPHYLLA
  !    36 = QUAKING ASPEN (AS)                POPULUS TREMULOIDES
  !    37 = CALIFORNIA-LAUREL (CL)            UMBELLULARIA CALIFORNICA
  !    38 = PACIFIC MADRONE (MA)              ARBUTUS MENZIESII
  !    39 = PACIFIC DOGWOOD (DG)              CORNUS NUTTALLII
  !    40 = BIGLEAF MAPLE (BM)                ACER MACROPHYLLUM
  !    41 = CURLLEAF MOUNTAIN-MAHOGANY (MC)   CERCOCARPUS LEDIFOLIUS
  !    42 = OTHER SOFTWOODS (OS)
  !    43 = OTHER HARDWOODS (OH)

  !  SURROGATE EQUATION ASSIGNMENT:

  !    FROM EXISTING WS EQUATIONS --
  !      USE 1(SP) FOR 11(WP) AND 24(MH)
  !      USE 2(DF) FOR 22(BD)
  !      USE 3(WF) FOR 13(SF)
  !      USE 4(GS) FOR 23(RW)
  !      USE 8(PP) FOR 18(MP)
  !      USE 34(TO) FOR 35(GC), 36(AS), 37(CL), 38(MA), AND 39(DG)
  !      USE 31(BO) FOR 28(LO), 29(CY), 30(BL), 32(VO), 33(IO), 40(BM), AND
  !                     43(OH)

  !    FROM CA VARIANT --
  !      USE CA11(KP) FOR 12(PM), 14(KP), 15(FP), 16(CP), 17(LM), 19(GP), 20(WE),
  !                       25(WJ), 26(WJ), AND 27(CJ)
  !      USE CA12(LP) FOR 9(LP) AND 10(WB)

  !    FROM SO VARIANT --
  !      USE SO30(MC) FOR 41(MC)

  !    FROM UT VARIANT --
  !      USE UT17(GB) FOR 21(GB)
  !      ALEXANDER 1967 RM32 USED AS A SITE REFERENCE; COEFFICIENTS WERE
  !      COPIED FROM THE SO VARIANT SPECIES 8=ES FOR THIS ROUTINE AND
  !      **SICHG**.

  !  DUMMY ARGUMENT NOT USED WARNING SUPPRESSION SECTION

  IDANUW = IFOR

  if (DEBUG) write(JOSTND,10)
  10 format(' ENTERING HTCALC')
  if (DEBUG)write(JOSTND,30)SINDX,ISPC,AG
  30 format(' IN HTCALC SINDX,ISPC,AG =',F10.2,I5,F10.3)

  ! GO TO A DIFFERENT POTENTIAL HEIGHT CURVE DEPENDING ON THE SPECIES

  select case (ISPC)

     !  IN 11 SPECIES WS, KING WAS USED FOR 1:6, 8, 11, 13, 18, 22:24, AND 42;
     !  THESE WERE CHANGED TO USE DUNNING IN THE 43 SPECIES VERSION.

     !  USE DUNNING-LEVITAN

  case(1:6,8:20,22:27,42)

     ! SET UP MAPPING TO THE CORRECT DUNNING-LEVITAN SITE CURVE

     if (SINDX .le.44.) then
        INDX = 6
     else if (SINDX.gt.44..and. SINDX.le.52.) then
        INDX = 5
     else if (SINDX.gt.52..and. SINDX.le.65.) then
        INDX = 4
     else if (SINDX.gt.65..and. SINDX.le.82.) then
        INDX = 3
     else if (SINDX.gt.82..and. SINDX.le.98.) then
        INDX = 2
     else
        INDX = 1
     end if
     if (AG .le.40.) then
        HGUESS = DUNL3(INDX) * AG
     else
        HGUESS = DUNL1(INDX) + DUNL2(INDX)*ALOG(AG)
     end if

     ! KING WAS USED FOR THESE SPECIES IN 11 SPECIES WS;
     ! CHANGED TO POWERS (1972) IN 43 SPECIES VERSION.
     ! 0.8 SCALER ADDED BY SMITH-MATEJA IN NC VARIANT SO TREES WOULD HIT THE
     ! SITE HEIGHT

  case(28:40,43)
     A = SQRT(AG) - SQRT(50.0)
     HGUESS = SINDX*(1.0+0.322*(A))-6.413*A
     HGUESS = HGUESS*.80

     ! DOLPH RED FIR CURVES PSW 206

  case(7)
     TERM = AG*EXP(AG*(-0.0440853))*1.4151E-6
     B = SINDX*TERM - 3.0495E6*TERM*TERM + 5.72474E-4
     TERM2 = 50.0 * EXP(50.0*(-0.0440853)) * 1.4151E-6
     B50 = SINDX*TERM2 - 3.0495E6*TERM2*TERM2 + 5.72474E-4
     HGUESS = ((SINDX-4.5)*(1.0-EXP(-B*(AG**1.51744)))) /&
          &(1.0-EXP(-B50*(50.0**1.51744)))
     HGUESS = HGUESS+4.5

     ! 41=MC - USE CURTIS, FOR. SCI. 20:307-316.  CURTIS CURVES
     ! ARE PRESENTED IN METRIC (3.2808 ?)

     ! BECAUSE OF EXCESSIVE HT GROWTH -- APPROX 30-40 FT/CYCLE, TOOK OUT
     ! THE METRIC MULTIPLIER. DIXON 11-05-92

  case(41)
     HGUESS = (SINDX - 4.5) / (0.6192 - 5.3394/(SINDX - 4.5)&
          &+ 240.29*AG**(-1.4) +(3368.9/(SINDX - 4.5))*AG**(-1.4))
     HGUESS = HGUESS + 4.5

     !  21=GB FROM THE CR VARIANT VIA UT.
     !  USE ALEXANDER 1967 RM32

  case(21)
     HGUESS = 4.5+((2.75780*SINDX**0.83312)*(1.0-EXP(-0.015701*AG))&
          &**(22.71944*SINDX**(-0.63557)))

  end select

  if (DEBUG)write(JOSTND,*)' LEAVING HTCALC HGUESS= ',HGUESS

  return
end
