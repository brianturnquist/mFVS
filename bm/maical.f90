!=========================================!
!   Compute stand mean annual increment   !
!=========================================!
! BM $Id$
subroutine MAICAL
  implicit none

  !  THIS SUBROUTINE CALCULATES THE MAI FOR THE STAND. IT IS CALLED
  !  FROM CRATET.

  ! Common blocks
  include 'PRGPRM.f90'
  include 'ARRAYS.f90'
  include 'COEFFS.f90'
  include 'CONTRL.f90'
  include 'HTCAL.f90'
  include 'OUTCOM.f90'
  include 'PLOT.f90'

  ! Variables
  logical :: DEBUG

  integer :: IERR,ISICD

  integer :: ISPNUM(MAXSP),ISPNUMTT(MAXSP)

  real    :: ADJMAI,SSSI

  !  DATA STATEMENTS

  !  SPECIES ORDER FOR BLUE MOUNTAINS VARIANT:
  !   1=WP,  2=WL,  3=DF,  4=GF,  5=MH,  6=WJ,  7=LP,  8=ES,
  !   9=AF, 10=PP, 11=WB, 12=LM, 13=PY, 14=YC, 15=AS, 16=CW,
  !  17=OS, 18=OH

  !  SPECIES EXPANSION:
  !  WJ USES SO JU (ORIGINALLY FROM UT VARIANT; REALLY PP FROM CR VARIANT)
  !  WB USES SO WB (ORIGINALLY FROM TT VARIANT)
  !  LM USES UT LM
  !  PY USES SO PY (ORIGINALLY FROM WC VARIANT)
  !  YC USES WC YC
  !  AS USES SO AS (ORIGINALLY FROM UT VARIANT)
  !  CW USES SO CW (ORIGINALLY FROM WC VARIANT)
  !  OS USES BM PP BARK COEFFICIENT
  !  OH USES SO OH (ORIGINALLY FROM WC VARIANT)

  data ISPNUM/119, 117, 202, 015, 264, 101, 108, 093, 021, 122,&
       &101, 101, 101, 042, 746, 746, 122, 746/

  !  TT SHARES THIS ROUTINE. SPECIES ORDER FOR TETONS VARIANT:
  !   1=WB,  2=LM,  3=DF,  4=PM,  5=BS,  6=AS,  7=LP,  8=ES,  9=AF, 10=PP,
  !  11=UJ, 12=RM, 13=BI, 14=MM, 15=NC, 16=MC, 17=OS, 18=OH

  !  TT VARIANT EXPANSION:
  !  BS USES ES EQUATIONS FROM TT
  !  PM USES PI (COMMON PINYON) EQUATIONS FROM UT
  !  PP USES PP EQUATIONS FROM CI
  !  UJ AND RM USE WJ (WESTERN JUNIPER) EQUATIONS FROM UT
  !  BI USES BM (BIGLEAF MAPLE) EQUATIONS FROM SO
  !  MM USES MM EQUATIONS FROM IE
  !  NC AND OH USE NC (NARROWLEAF COTTONWOOD) EQUATIONS FROM CR
  !  MC USES MC (CURL-LEAF MTN-MAHOGANY) EQUATIONS FROM SO
  !  OS USES OT (OTHER SP.) EQUATIONS FROM TT

  data ISPNUMTT/&
       &101, 101, 202, 101, 093, 746, 108, 093, 019, 122,&
       &101, 101, 746, 746, 101, 746, 101, 101/

  ! Check whether debugging is enabled
  call DBCHK (DEBUG,'MAICAL',6,ICYC)

  if (DEBUG) write(JOSTND,3)ICYC
  3 format(' ENTERING SUBROUTINE MAICAL  CYCLE =',I5)

  !   RMAI IS FUNCTION TO CALCULATE ADJUSTED MAI.

  if (ISISP .eq.0) ISISP = 3
  SSSI = SITEAR(ISISP)
  if (SSSI .eq.0.) SSSI = 140.0
  if (VARACD .eq. 'TT') then
     ISICD = ISPNUMTT(ISISP)
  else
     ISICD = ISPNUM(ISISP)
  end if
  RMAI = ADJMAI(ISICD,SSSI,10.0,IERR)
  if (RMAI .gt.128.0)RMAI = 128.0
  if (DEBUG) write(JOSTND,10)ICYC,RMAI
  10 format(' LEAVING SUBROUTINE MAICAL  CYCLE =',I5,5X,'RMAI =',F10.3)
  return
end
