  !          1 = douglas-fir (west OR)
  !          2 = douglas-fir (west WA)
  !          3 = douglas-fir (east OR)
  !          4 = douglas-fir (east WA)
  !          5 = western white pine
  !          6 = western larch
  !          7 = redcedar
  !          8 = madrone
  !          9 = lodgepole pine
  !          10 = spruce
  !          11 = western hemlock
  !          12 = mountain hemlock
  !          13 = ponderosa pine (OR)
  !          14 = ponderosa pine (WA)
  !          15 = pacific silver fir (OR)
  !          16 = pacific silver fir (WA)
  !          17 = grand / white fir
  !          18 = misc. hardwoods
  !          19 = populus
  !          20 = alders

