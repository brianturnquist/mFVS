! FIRE-VBASE $Id$
subroutine FMR6FALL(KSP,SML,JADJ,X)
  implicit none

  !     CALLED FROM: FMSNAG

  !  Purpose:
  !     This subroutine calculates the proportion of snags in a record that
  !     will fall in a given year.  This is based on species, plant association,
  !     size, and an adjustment factor based on snag decay (see fmr6sdcy).

  !     The calculations are based on work done by Kim Mellen, regional
  !     wildlife ecologist for region 6.

  !  Local variable definitions:
  !     KSP -  species of the snag
  !     X - the proportion of snags to fall
  !     JADJ - the adjustment factor based on snag decay
  !         (1 = decrease, 2 = none, 3 = increase)

