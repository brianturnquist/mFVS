!====================!
!   wsbwe : bwedie   !
!====================!
! WSBWE $Id$
subroutine BWEDIE(ISTAGE,IC,IH,EATFOL,GODISP,SPRDIE,TOTDIE)
  implicit none

  ! THIS SUBROUTINE CALCULATES SURVIVAL FOR SMALL LARVAE (ISTAGE=1),
  ! LARGE LARVAE (ISTAGE=2), OR PUPAE (ISTAGE=3).

  !  K.A. SHEEHAN  USDA-FS, R6-NATURAL RESOURCES, PORTLAND, OR

  !   CALLED FROM: BWELIT

  !   SUBROUTINES CALLED: BWESLP

  !   PARAMETERS:

  !   ACTNEW - ACTUAL AMOUNT OF NEW FOLIAGE GROWN & NOT EATEN TO DATE
  !   ANT_BD - PROP. OF PREDATOR MORTALITY ASSIGNED TO ANTS (BY CROWN LEVEL);
  !            (1.0-ANT_BD) = PROP. ASSIGNED TO BIRDS
  !   ANTDEN - ANT DENSITY FACTOR (SET TO 1.0 NOW)
  !   ANTSI  - INSTANTANEOUS MORT. RATE FOR LARVAE KILLED BY ANTS
  !   ANTS   - PROP. OF BW KILLED BY ANTS DURING THIS LIFE STAGE
  !   BIRDEN - BIRD DENSITY FACTOR (SET TO 1.0 NOW)
  !   BIRDS  - PROP. OF BW KILLED BY BIRDS DURING THIS LIFE STAGE
  !   BIRDSI - INSTANTANEOUS MORT. RATE FOR LARVAE KILLED BY BIRDS
  !   BW     - NO. OF BUDWORMS PRESENT BY CELL
  !   BWNEW  - NO. OF LARVAE THAT COULD EAT NEW FOLIAGE (GIVEN AMT NEW PRESENT)
  !   DAYS   - NO. OF DAYS SPENT IN A LIFE STAGE
  !   DEFYRS - NO. OF YEARS WITH >20% DEFOL. BY HOST (THIS OUTBREAK ONLY)
  !   DISPI  - INSTANTANEOUS MORT. RATE FOR DISPERSING LARVAE
  !   EATEN  - AMOUNT OF FOLIAGE EATEN BY SMALL OR LARGE LARVAE BY HOST
  !   EATFOL - AMT. OF FOLIAGE EATEN BY LARVAE THAT DIED LATER IN THIS TIME STEP
  !   FOLDVX - SLIP FUNCT. TO CONVERT NO. OF YEARS OF DEFOLIATION (DEFYRS)
  !            TO RELATIVE FOL. QUALITY -- EFFECTS ON DEVEL. RATES (X VALUES)
  !   FOLDVY - SLIP FUNCT. TO CONVERT NO. OF YEARS OF DEFOLIATION (DEFYRS)
  !            TO RELATIVE FOL. QUALITY -- EFFECTS ON DEVEL. RATES (Y VALUES)
  !   FOLQL  - FOLIAGE QUALITY INDEX (SEE FOLDVX, FOLDVY)
  !   GODISP - NO. (LATER PROP.) OF LARVAE THAT DISPERSE
  !   ISTAGE - LIFE STAGE INDEX: 1=SMALL LARVAE, 2=LARGE LARVAE, 3=PUPAE
  !   M1PRED - MYSTERY_1 PREDATOR MULTIPLIER (SET TO 1.0 NOW)
  !   M2PRED - MYSTERY_2 PREDATOR MULTIPLIER (SET TO 1.0 NOW)
  !   M3PRED - MYSTERY_3 PREDATOR MULTIPLIER (SET TO 1.0 NOW)
  !   MYST1  - PROP. OF BW KILLED BY MYSTERY_1 DURING THIS LIFE STAGE
  !   MYST2  - PROP. OF BW KILLED BY MYSTERY_2 DURING THIS LIFE STAGE
  !   MYST3  - PROP. OF BW KILLED BY MYSTERY_3 DURING THIS LIFE STAGE
  !   MYST1I  - INSTANTANEOUS MORT. RATE FOR BW KILLED BY MYSTERY_1
  !   MYST2I  - INSTANTANEOUS MORT. RATE FOR BW KILLED BY MYSTERY_2
  !   MYST3I  - INSTANTANEOUS MORT. RATE FOR BW KILLED BY MYSTERY_3
  !   MYS1DN - MYSTERY_1 DENSITY FACTOR (SET TO 0.0 NOW)
  !   MYS2DN - MYSTERY_2 DENSITY FACTOR (SET TO 0.0 NOW)
  !   MYS3DN - MYSTERY_3 DENSITY FACTOR (SET TO 0.0 NOW)
  !   NEMULT - USER-SPECIFIED MULTIPLIER USED TO CHANGE PREDATION RATES
  !   OBPHAS - STORES PARASITISM RATES BY OUTBREAK PHASE AND LIFE STAGE
  !   OBPHX  - SLIP FUNC. TO CONVERT YEARS OF DEFOLIATION (DEFYRS) TO PARA. RATE
  !   OBPHY  - SLIP FUNC. TO CONVERT YEARS OF DEFOLIATION (DEFYRS) TO PARA. RATE
  !   OUT1   - STORES INFO. FOR TABLE 1 (SEE P1.FOR FOR DETAILS)
  !   OUT3   - STORES INFO. FOR TABLE 3 (SEE P3.FOR FOR DETAILS)
  !   PARASI - INSTANTANEOUS MORT. RATE FOR LARVAE KILLED BY PARASITES
  !   PREDKL - NO. OF BW KILLED BY PREDATORS ACC'DING TO CAMPBELL & SRIVASTAVA
  !   PRATE  - PREDATION RATE (CAMPBELL & STRIVASTAVA)
  !   RATIO  - PROPORTION OF LARVAE THAT ARE ABLE TO EAT NEW FOLIAGE
  !   SPRAYI - INSTANTANEOUS MORT. RATE FOR BW KILLED BY INSECTICIDE SPRAY
  !   SPRDIE - PROP. OF DEAD BW THAT WERE KILLED BY SPRAY
  !   SSTARX - SLIP FUNCT. TO CONVERT RATIO TO PROP. OF LARVAE
  !            THAT STARVE WHEN THERE ISN'T ENOUGH NEW FOL. (X VALUES)
  !   SSTARY - SLIP FUNCT. TO CONVERT RATIO TO PROP. OF LARVAE
  !            THAT STARVE WHEN THERE ISN'T ENOUGH NEW FOL. (Y VALUES)
  !   STARV  - PROPORTION OF LARVAE THAT STARVE
  !   STARVI - INSTANTANEOUS MORT. RATE FOR STARVING LARVAE
  !   STARVX - STORES SSTARX VALUES FOR THE 3 LIFE STAGES
  !   STARVY - STORES SSTARY VALUES FOR THE 3 LIFE STAGES
  !   TOTAM  - TOTAL ACTUAL MORTALITY RATE
  !   TOTDIE - NO. OF BW THAT DIE
  !   TOTIR  - TOTAL INSTANTANEOUS MORTALITY RATE
  !   WASTED - AMOUNT OF FOLIAGE WASTED PER LARVA

  ! Revision History:
  !  17-MAY-2005 Lance R. David (FHTET)
  !     Added FVS parameter file PRGPRM.F77.
  !  14-JUL-2010 Lance R. David (FMSC)
  !     Added IMPLICIT NONE and declared variables as needed.

  ! Common blocks
  include 'PRGPRM.f90'
  include 'BWESTD.f90'
  include 'BWECOM.f90'
  include 'BWECM2.f90'
  include 'BWEBOX.f90'

  ! Variables
  integer :: IC,IH,ISTAGE,K
  real    :: ANTS,ANTSI,BIRDS,BIRDSI,BWESLP,BWNEW,DAYNEW,DISPI,EATFOL,EATMAX,FOLQL,GODISP,PARAS,&
       &PARASI,POTCLP,PREDKL,RATIO,SAVKIL(9,6),SPRAY,SPRAYI,SPRDIE,SSTARX(4),SSTARY(4),STARV,STARVI,TOTAM,&
       &TOTDIE,TOTIR,X,Y
  real    :: MYST1,MYST2,MYST3,MYST1I,MYST2I,MYST3I

  !     WRITE (16,*)'ENTER BWEDIE: ISTAGE,IC,IH=',ISTAGE,IC,IH      ! TEMP DEBUG
  !     WRITE (16,*)'ENTER BWEDIE: BW(IC,IH)=',BW(IC,IH)            ! TEMP DEBUG

  ! Initialize variables
  SPRDIE = 0.0
  TOTDIE = 0.0
  EATFOL = 0.0
  EATMAX = 0.0
  POTCLP = 0.0
  FOLQL = 0.0
  PREDKL = 0.0
  GODISP = 0.0
  STARV = 0.0
  ANTS = 0.0
  BIRDS = 0.0
  PARAS = 0.0
  MYST1 = 0.0
  MYST2 = 0.0
  MYST3 = 0.0
  SPRAY = 0.0

  !  IF VIRTUALLY NO LARVAE ARE PRESENT, THEN NO LARVAE DIE (DUH...)

  if (BW(IC,IH).lt.1.0) go to 900 ! RETURN

  !  HANDLE STARVATION ONLY FOR LARVAE.  PUPAE DON'T STARVE.

  if (ISTAGE.eq.3) goto 40

  !  IF VIRTUALLY NO FOLIAGE IS PRESENT, THEN MOST LARVAE STARVE.

  if (ACTNEW(IC,IH).lt.1.0) then
     STARV = STARVY(ISTAGE,1)
     go to 40
  end if

  !  CALCULATE POTENTIAL AMOUNT OF FOLIAGE CLIPPED
  !  IF THERE'S ENOUGH FOLIAGE, THEN NOBODY STARVES.

  POTCLP = BW(IC,IH)*EATEN(ISTAGE,IH)/(1.0-WASTED(ISTAGE))
  if (POTCLP.le.ACTNEW(IC,IH)) then
     continue

     !  IF THERE ISN'T ENOUGH FOLIAGE, CALC. THE PROPORTION THAT STARVE.

  else
     BWNEW = ACTNEW(IC,IH)*(1.0-WASTED(ISTAGE))/EATEN(ISTAGE,IH)
     RATIO = 1.0
     if (BW(IC,IH).gt.1.0) RATIO = BWNEW/BW(IC,IH)
     do K = 1,4
        SSTARX(K) = STARVX(ISTAGE,K)
        SSTARY(K) = STARVY(ISTAGE,K)
        30 continue
     end do
     STARV = BWESLP(RATIO,SSTARX,SSTARY,4)

     !  STARVING LARVAE EAT SOME FOLIAGE - ARBITRARILY SET TO 50% OF POTENTIAL
     !  BUT! DON'T LET LARVAE EAT EVERY SINGLE NEEDLE.  LIMIT THEM ARBITRARILY TO
     !  85% OF WHAT'S THERE.

     EATFOL = (POTCLP-ACTNEW(IC,IH))*.5
     EATMAX = ACTNEW(IC,IH)*.85
     if (EATFOL.gt.EATMAX) EATFOL = EATMAX
  end if

  40 continue

  !  NEXT DEAL WITH PREDATORS AND MYSTERY MORTALITY SOURCES

  X = 1.0
  FOLQL = BWESLP(DEFYRS(IH),FOLDVX,FOLDVY,4)
  if (ISTAGE.eq.1) then
     DAYNEW = DAYS(1)*.333*FOLQL
     Y = EXP(PRATE(IC)*DAYNEW)
  else if (ISTAGE.eq.2) then
     Y = EXP(PRATE(IC)*DAYS(ISTAGE)*FOLQL)
     SAVKIL(IC,IH) = Y
  else
     DAYNEW = DAYS(2)+DAYS(3)
     Y = EXP(PRATE(IC)*DAYNEW)
     X = SAVKIL(IC,IH)
  end if
  PREDKL = BW(IC,IH)*(X-Y)
  ANTS = ANTDEN(IC,IH)*PREDKL*ANT_BD(IC)*NEMULT(1,ISTAGE)/BW(IC,IH)
  BIRDS = BIRDEN(IC,IH)*PREDKL*(1.0-ANT_BD(IC))*NEMULT(2,ISTAGE)&
       &/BW(IC,IH)

  !     WRITE (16,*) 'IN BWEDIE: POTCLP, STARV =',POTCLP, STARV     ! TEMP DEBUG
  !     WRITE (16,*) 'IN BWEDIE: EATFOL, EATMAX =',EATFOL,EATMAX    ! TEMP DEBUG
  !     WRITE (16,*) 'IN BWEDIE: FOLQL, PREDKL =',FOLQL,PREDKL      ! TEMP DEBUG
  !     WRITE (16,*) 'IN BWEDIE: ANTS, BIRDS =',ANTS,BIRDS          ! TEMP DEBUG

  !  PARAS. RATE IS A FUNCTION OF HOW LONG THE OUTBREAK HAS BEEN
  !  GOING ON IN THIS STAND (DEFYRS) AND IS NOT A FACTOR IN STAGE 1
  !  OF AN OUTBREAK.

  if (ISTAGE.ne.1) then
     OBPHY(1) = OBPHAS(ISTAGE,1)
     OBPHY(2) = OBPHAS(ISTAGE,1)
     OBPHY(3) = OBPHAS(ISTAGE,2)
     OBPHY(4) = OBPHAS(ISTAGE,2)
     PARAS = BWESLP(DEFYRS(IH),OBPHX,OBPHY,4)
     PARAS = PARAS*NEMULT(3,ISTAGE)
  end if
  MYST1 = MYS1DN(IC,IH)*DAYS(ISTAGE)*M1PRED(ISTAGE)*WRAIN1(ISTAGE)*&
       &NEMULT(4,ISTAGE)/BW(IC,IH)
  MYST2 = MYS2DN(IC,IH)*DAYS(ISTAGE)*M2PRED(ISTAGE)*WRAIN2(ISTAGE)*&
       &NEMULT(4,ISTAGE)/BW(IC,IH)
  MYST3 = MYS3DN(IC,IH)*DAYS(ISTAGE)*M3PRED(ISTAGE)*WRAIN3(ISTAGE)*&
       &NEMULT(4,ISTAGE)/BW(IC,IH)

  !     WRITE (16,*) 'IN BWEDIE: MYST1-2-3 =',MYST1,MYST2,MYST3      ! TEMP DEBUG

  GODISP = GODISP/BW(IC,IH)

  !     WRITE (16,*) 'IN BWEDIE: GODISP =',GODISP                    ! TEMP DEBUG

  !  DEAL WITH INSECTICIDE APPLICATION (LARGE LARVAE ONLY)

  if (LSPRAY.and.ISTAGE.eq.2) then
     SPRAY = SPEFF/100.0
  else
     SPRAY = 0.0
  end if

  !  CONVERT TO INSTANTANEOUS MORTALITY RATES

  if (GODISP.gt.0.99) GODISP = 0.99
  if (STARV.gt.0.99) STARV = 0.99
  if (ANTS.gt.0.99) ANTS = 0.99
  if (BIRDS.gt.0.99) BIRDS = 0.99
  if (PARAS.gt.0.99) PARAS = 0.99
  if (MYST1.gt.0.99) MYST1 = 0.99
  if (MYST2.gt.0.99) MYST2 = 0.99
  if (MYST3.gt.0.99) MYST3 = 0.99
  if (SPRAY.gt.0.99) SPRAY = 0.99
  DISPI = -LOG(1.0-GODISP)
  STARVI = -LOG(1.0-STARV)
  ANTSI = -LOG(1.0-ANTS)
  BIRDSI = -LOG(1.0-BIRDS)
  PARASI = -LOG(1.0-PARAS)
  MYST1I = -LOG(1.0-MYST1)
  MYST2I = -LOG(1.0-MYST2)
  MYST3I = -LOG(1.0-MYST3)
  SPRAYI = -LOG(1.0-SPRAY)
  TOTIR = DISPI+STARVI+ANTSI+BIRDSI+PARASI+&
       &MYST1I+MYST2I+MYST3I+SPRAYI

  !     WRITE (16,*) 'IN BWEDIE: TOTIR =',TOTIR                      ! TEMP DEBUG

  !  CONVERT BACK TO ACTUAL MORTALITY, AND PARTITION TO SOURCES

  TOTAM = 1.0-EXP(-TOTIR)
  TOTDIE = TOTAM*BW(IC,IH)
  BW(IC,IH) = BW(IC,IH)-TOTDIE
  if (TOTIR.le.0.0) go to 900 ! RETURN
  SPRDIE = SPRAYI/TOTIR

  !  SAVE NO. OF BW KILLED FOR OUTPUT TABLE (P1)

  OUT1(IC,IH,3) = TOTDIE*DISPI/TOTIR
  OUT1(IC,IH,4) = TOTDIE*STARVI/TOTIR
  OUT1(IC,IH,5) = TOTDIE*ANTSI/TOTIR
  OUT1(IC,IH,6) = TOTDIE*BIRDSI/TOTIR
  OUT1(IC,IH,7) = TOTDIE*PARASI/TOTIR
  OUT1(IC,IH,8) = TOTDIE*(MYST1I+MYST2I+MYST3I)/TOTIR
  if (ISTAGE.eq.1) then
     OUT3(IC,IH,3) = TOTDIE*STARVI/TOTIR
     OUT3(IC,IH,4) = TOTDIE*(ANTSI+BIRDSI+MYST1I+&
          &MYST2I+MYST3I)/TOTIR
     OUT3(IC,IH,18) = TOTDIE*PARASI/TOTIR
     !        sumdie=out3(ic,ih,3)+out3(ic,ih,4)+out3(ic,ih,18)
  else if (ISTAGE.eq.2) then
     OUT3(IC,IH,5) = OUT3(IC,IH,5)+(TOTDIE*(DISPI+STARVI)/TOTIR)
     OUT3(IC,IH,6) = TOTDIE*(ANTSI+BIRDSI+MYST1I+&
          &MYST2I+MYST3I)/TOTIR
     OUT3(IC,IH,19) = TOTDIE*PARASI/TOTIR
     OUT3(IC,IH,17) = TOTDIE*SPRAYI/TOTIR
     !        sumdie=out3(ic,ih,5)+out3(ic,ih,6)+out3(ic,ih,17)+
     !     *     out3(ic,ih,19)
  else
     OUT3(IC,IH,7) = TOTDIE*(ANTSI+BIRDSI+MYST1I+&
          &MYST2I+MYST3I)/TOTIR
     OUT3(IC,IH,20) = TOTDIE*PARASI/TOTIR
     !        sumdie=out3(ic,ih,7)+out3(ic,ih,20)
  end if
  !      diff=totdie-sumdie
  !      sumdie=0.0

  900 continue

  !     WRITE (16,*) 'IN BWEDIE: ISTAGE, IC, IH=',ISTAGE,IC,IH       ! TEMP DEBUG
  !     WRITE (16,*) 'IN BWEDIE: BW(IC,IH)=',BW(IC,IH)               ! TEMP DEBUG
  !     WRITE (16,*) 'IN BWEDIE: EATFOL,GODISP=',EATFOL,GODISP       ! TEMP DEBUG
  !     WRITE (16,*) 'IN BWEDIE: SPRDIE,TOTDIE=',SPRDIE,TOTDIE       ! TEMP DEBUG

  return
end
