subroutine EXPPNB
  implicit none

  !     VARIANT DEPENDENT EXTERNAL REFERENCES FOR THE
  !     PARALLEL PROCESSING EXTENSION

  !     CALLED TO COMPUTE THE DDS MODIFIER THAT ACCOUNTS FOR THE DENSITY
  !     OF NEIGHBORING STANDS (CALLED FROM DGF).

  ! Variables
  real    :: BDBL,BBAL,BCCF,DBH,CCFO,BALO,XPPDDS,XPPMLT
  real    :: RDANUW

  !  ENTRY PPDGF

  entry PPDGF (XPPDDS,BALO,CCFO,DBH,BCCF,BBAL,BDBL)

  !  DUMMY ARGUMENT NOT USED WARNING SUPPRESSION SECTION

  RDANUW = XPPDDS
  RDANUW = BALO
  RDANUW = CCFO
  RDANUW = DBH
  RDANUW = BCCF
  RDANUW = BBAL
  RDANUW = BDBL

  return

  !  ENTRY PPREGT

  !     CALLED TO COMPUTE THE REGENT MULTIPLIER THAT ACCOUNTS FOR
  !     THE DENSITY OF NEIGHBORING STANDS (CALLED FROM REGENT).

  entry PPREGT (XPPMLT,CCFO,BALO,BCCF,BBAL)

  !  DUMMY ARGUMENT NOT USED WARNING SUPPRESSION SECTION

  RDANUW = XPPMLT
  RDANUW = CCFO
  RDANUW = BALO
  RDANUW = BCCF
  RDANUW = BBAL

  return
end
