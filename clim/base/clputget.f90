!==========================!
!   clim/base : clputget   !
!==========================!
! CLIM-BASE $Id$
subroutine CLPUT (WK3,IPNT,ILIMIT)
  implicit none

  !     CLIMATE EXTENSION - STORES THE CLIMATE COMMON

  ! Common blocks
  include 'PRGPRM.f90'
  include 'CLIMATE.f90'

  ! Variables
  integer :: MXI,MXR,I
  parameter (MXI = 23,MXR = 4)
  integer :: INTS(MXI)
  real    :: WK3(*),REALS(MXR)
  integer :: IPNT,ILIMIT

  if (.not. LCLIMATE) return

  INTS( 1) = NATTRS
  INTS( 2) = NYEARS
  INTS( 3) = IXDD5
  INTS( 4) = IXMTCM
  INTS( 5) = IXMAT
  INTS( 6) = IXMAP
  INTS( 7) = IXMTWM
  INTS( 8) = IXGSP
  INTS( 9) = IXGSDD5
  INTS(10) = IXD100
  INTS(11) = IXMMIN
  INTS(12) = IXDD0
  INTS(13) = IXPSITE
  INTS(14) = NESPECIES
  INTS(15) = JCLREF
  INTS(16) = IDEmtwm
  INTS(17) = IDEmtcm
  INTS(18) = IDEdd5
  INTS(19) = IDEsdi
  INTS(20) = IDEdd0
  INTS(21) = IDEmapdd5
  INTS(22) = 0
  if (LAESTB) INTS(22) = 1
  INTS(23) = CLHABINDX
  call IFWRIT (WK3,IPNT,ILIMIT,INTS,MXI,2)
  call IFWRIT (WK3,IPNT,ILIMIT,INDXSPECIES,MAXSP,2)
  call IFWRIT (WK3,IPNT,ILIMIT,YEARS,NYEARS,2)

  REALS( 1) = AESNTREES
  REALS( 2) = AESTOCK
  REALS( 3) = CLMXDENMULT
  REALS( 4) = MXDENMLT
  call BFWRIT (WK3,IPNT,ILIMIT,REALS,MXR,2)
  call BFWRIT (WK3,IPNT,ILIMIT,CLGROWMULT,MAXSP,2)
  call BFWRIT (WK3,IPNT,ILIMIT,CLMRTMLT1,MAXSP,2)
  call BFWRIT (WK3,IPNT,ILIMIT,CLMRTMLT2,MAXSP,2)
  do I = 1,NATTRS
     call BFWRIT (WK3,IPNT,ILIMIT,ATTRS(1,I),NYEARS,2)
  end do
  call BFWRIT (WK3,IPNT,ILIMIT,POTESTAB,MAXSP,2)
  call BFWRIT (WK3,IPNT,ILIMIT,SPMORT1,MAXSP,2)
  call BFWRIT (WK3,IPNT,ILIMIT,SPMORT2,MAXSP,2)
  call BFWRIT (WK3,IPNT,ILIMIT,SPGMULT,MAXSP,2)
  call BFWRIT (WK3,IPNT,ILIMIT,SPSITGM,MAXSP,2)
  call BFWRIT (WK3,IPNT,ILIMIT,SPVIAB,MAXSP,2)
  call BFWRIT (WK3,IPNT,ILIMIT,SPCALIB,MAXSP,2)

  return
end

subroutine CLGET (WK3,IPNT,ILIMIT)
  implicit none

  !     CLIMATE EXTENSION - GETS THE CLIMATE COMMON

  ! Common blocks
  include 'PRGPRM.f90'
  include 'CLIMATE.f90'

  ! Variables
  integer :: MXI,MXR,I
  parameter (MXI = 23,MXR = 4)
  integer :: INTS(MXI)
  real    :: WK3(*),REALS(MXR)
  integer :: IPNT,ILIMIT

  if (.not. LCLIMATE) return

  call IFREAD (WK3,IPNT,ILIMIT,INTS,MXI,2)
  NATTRS = INTS( 1)
  NYEARS = INTS( 2)
  IXDD5 = INTS( 3)
  IXMTCM = INTS( 4)
  IXMAT = INTS( 5)
  IXMAP = INTS( 6)
  IXMTWM = INTS( 7)
  IXGSP = INTS( 8)
  IXGSDD5 = INTS( 9)
  IXD100 = INTS(10)
  IXMMIN = INTS(11)
  IXDD0 = INTS(12)
  IXPSITE = INTS(13)
  NESPECIES = INTS(14)
  JCLREF = INTS(15)
  IDEmtwm = INTS(16)
  IDEmtcm = INTS(17)
  IDEdd5 = INTS(18)
  IDEsdi = INTS(19)
  IDEdd0 = INTS(20)
  IDEmapdd5 = INTS(21)
  LAESTB = INTS(22).eq.1
  CLHABINDX = INTS(23)
  call IFREAD (WK3,IPNT,ILIMIT,INDXSPECIES,MAXSP,2)
  call IFREAD (WK3,IPNT,ILIMIT,YEARS,NYEARS,2)

  call BFREAD (WK3,IPNT,ILIMIT,REALS,MXR,2)
  AESNTREES = REALS( 1)
  AESTOCK = REALS( 2)
  CLMXDENMULT = REALS( 3)
  MXDENMLT = REALS( 4)
  call BFREAD (WK3,IPNT,ILIMIT,CLGROWMULT,MAXSP,2)
  call BFREAD (WK3,IPNT,ILIMIT,CLMRTMLT1,MAXSP,2)
  call BFREAD (WK3,IPNT,ILIMIT,CLMRTMLT2,MAXSP,2)
  do I = 1,NATTRS
     call BFREAD (WK3,IPNT,ILIMIT,ATTRS(1,I),NYEARS,2)
  end do
  call BFREAD (WK3,IPNT,ILIMIT,POTESTAB,MAXSP,2)
  call BFREAD (WK3,IPNT,ILIMIT,SPMORT1,MAXSP,2)
  call BFREAD (WK3,IPNT,ILIMIT,SPMORT2,MAXSP,2)
  call BFREAD (WK3,IPNT,ILIMIT,SPGMULT,MAXSP,2)
  call BFREAD (WK3,IPNT,ILIMIT,SPSITGM,MAXSP,2)
  call BFREAD (WK3,IPNT,ILIMIT,SPVIAB,MAXSP,2)
  call BFREAD (WK3,IPNT,ILIMIT,SPCALIB,MAXSP,2)

  return
end

subroutine CLACTV(L)

  ! Common blocks
  include 'PRGPRM.f90'
  include 'CLIMATE.f90'

  ! Variables
  logical :: L
  L = LCLIMATE
  return
  entry CLSETACTV(L)
  LCLIMATE = L
  return
end
