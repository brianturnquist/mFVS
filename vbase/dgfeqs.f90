!==============================================!
!   Diameter growth equations shared by DGFs   !
!==============================================!
! VBASE $Id$

!  EACH ROUTINE HOLDS ONE EQUATION THAT SEVERAL VARIANTS' **DGF** USE
!  UNCHANGED.  CALLERS KEEP THEIR OWN SPECIES SELECTION, TREE VARIABLES,
!  BARK CALLS, DIAGNOSTICS, PERIOD CONVERSION AND FINAL CLAMP.

subroutine DGFRWGS(I,ISPC,D,CR,BAL,PRD,CONSPP,DEBUG,PBAL,DDS)
  implicit none

  !  GIANT SEQUOIA AND COASTAL REDWOOD (EQUATIONS FIT BY MARK CASTLE IN
  !  2019), USED BY CA, OC, OP, PN, WC AND WS.  RETURNS LN(DDS) FOR THE
  !  10-YEAR PERIOD WITH COR AND COR2 APPLIED; COR2 IS NOT ADDED TO DGCON
  !  FOR THESE SPECIES.  PBAL IS RETURNED FOR THE CALLER'S DIAGNOSTICS.

  include 'PRGPRM.f90'
  include 'ARRAYS.f90'
  include 'COEFFS.f90'
  include 'CONTRL.f90'
  include 'PLOT.f90'
  include 'VARCOM.f90'

  integer :: I,ISPC
  real    :: D,CR,BAL,PRD,CONSPP,PBAL,DDS,DGLT,BRAT
  logical :: DEBUG

  PBAL = PTBAA(ITRE(I))*(1.0-(PCT(I)/100.))
  if (PBAL .lt.0.) PBAL = BAL
  call RWGSDG(ISPC,D,HT(I),CR,PBAL,PRD,CONSPP,DGLT,BRAT,DDS)

  !  RW/GS DEBUG
  if (DEBUG)write(JOSTND,*)'IN DGF - RW/GS DEBUG ',' D=',D,&
       &' PBAL=',PBAL,' PRD=',PRD,' CR=',CR,' SI=',SITEAR(ISPC),&
       &' SLP=',SLOPE*100,' ASP=',ASPECT, ' BRAT=',BRAT,&
       &' DGLT=', DGLT,' DDS=',DDS

  !  APPLY COR AND COR2 TO DDS
  DDS = DDS + COR(ISPC) + LOG(COR2(ISPC))
  if (DEBUG)write(JOSTND,*)'IN DGF - RW/GS DEBUG ',' DDS=',DDS,&
       &' COR(ISPC)=',COR(ISPC),' COR2(ISPC)=',COR2(ISPC)
  return
end subroutine DGFRWGS

subroutine RWGSDG(ISPC,D,H,CR,PBAL,PRD,CONSPP,DGLT,BRAT,DDS)
  implicit none

  !  GS/RW OUTSIDE-BARK DIAMETER INCREMENT DGLT, CONVERTED WITH THE
  !  SPECIES BARK RATIO BRAT TO LN(CHANGE IN SQUARED INSIDE-BARK
  !  DIAMETER).  CONSPP IS DGCON(ISPC) = -3.502444 + 0.415435*LN(SITE).
  !  ALSO CALLED DIRECTLY BY NC, WHICH HAS ITS OWN DIAGNOSTICS.

  include 'PRGPRM.f90'
  include 'PLOT.f90'

  integer :: ISPC
  real    :: D,H,CR,PBAL,PRD,CONSPP,DGLT,BRAT,DDS
  real    :: BRATIO,TEMPD1,TEMPD2,DUP

  DGLT = EXP(CONSPP + 0.185911*LOG(D) -0.000073*D*D&
       &-0.001796*PBAL - 0.42078*PRD + 0.589318*LOG(CR*100)&
       &-0.000926*SLOPE*100 - 0.002203*(SLOPE*100)*COS(ASPECT))

  !  CONVERT OUTSIDE BARK DIAMETER INCREMENT TO INSIDE BARK
  !  CHANGE IN SQUARED DIAMETERS.
  BRAT = BRATIO(ISPC,D,H)
  TEMPD1 = D * BRAT ! CURRENT DIB
  DUP = D + DGLT ! WITH GROWTH DOB
  TEMPD2 = DUP * BRAT ! WITH GROWTH DIB

  !  LOG OF CHANGE IN DIB SQUARED FOR THE PERIOD
  DDS = LOG(TEMPD2**2 - TEMPD1**2)
  return
end subroutine RWGSDG

subroutine DGFRA(ISPC,D,BARK,DIAGR,DDS)
  implicit none

  !  RED ALDER, USED BY EC, SO, OP, PN AND WC WITH THE CALLER'S BARK
  !  RATIO.  FUNCTION BOTTOMS OUT AT D=18. DECREASE LINERALY AFTER THAT TO
  !  DG=0 AT D=28, AND LIMIT TO .1 ON LOWER END.  GED 4-15-93.
  !  RETURNS DIAMETER INCREMENT DIAGR AND LN(DDS) WITH COR2 AND COR.

  include 'PRGPRM.f90'
  include 'COEFFS.f90'
  include 'PLOT.f90'

  integer :: ISPC
  real    :: D,BARK,DIAGR,DDS,CONST

  CONST = 3.250531 - 0.003029*BA
  if (D .le.18.) then
     DIAGR = CONST - 0.166496*D + 0.004618*D*D
  else
     DIAGR = CONST - (CONST/10.)*(D-18.)
  end if
  if (DIAGR .lt.0.1) DIAGR = 0.1
  DDS = ALOG(DIAGR*(2.0*D*BARK+DIAGR))+ALOG(COR2(ISPC))+COR(ISPC)
  return
end subroutine DGFRA

real function DGFJUN(DPP,BATEM,SI)
  implicit none

  !  JUNIPER/PINYON FUTURE DIAMETER (FROM THE UT VARIANT), USED BY BM, CI,
  !  CR, EM, IE, SO, TT, UT AND WS.  DPP IS THE CURRENT DIAMETER FLOORED AT
  !  1 INCH AND BATEM THE CALLER'S FLOORED STAND BASAL AREA.  THE PERIOD
  !  INCREMENT IS LIMITED TO ONE INCH; CALLERS APPLY THEIR OWN LOWER BOUND,
  !  STAGNATION, BARK CONVERSION AND CORRECTION.

  real :: DPP,BATEM,SI

  DGFJUN = 0.25897 + 1.03129 * DPP - 0.0002025464 * BATEM&
       &+ 0.00177 * SI
  if ((DGFJUN-DPP) .gt.1.0) DGFJUN = DPP + 1.0
  return
end function DGFJUN

real function DGFCOA(DPP,BA,SI)
  implicit none

  !  COTTONWOOD/HARDWOOD FUTURE DIAMETER, SWMC FORM (FROM THE CR VARIANT),
  !  USED BY CI, EM, IE AND CR (MODEL TYPES 1-2).  CI/EM/IE THEN LIMIT
  !  IT TO 36 INCHES; CR DOES NOT.

  real :: DPP,BA,SI

  DGFCOA = 0.24506 + 1.01291 * DPP - 0.00084659 * BA&
       &+ 0.00631*SI
  return
end function DGFCOA

real function DGFCOB(DPP,BATEM,SI,BAUTBA)
  implicit none

  !  COTTONWOOD/HARDWOOD FUTURE DIAMETER, ASPEN MODEL-TYPE FORM (FROM THE
  !  CR VARIANT), USED BY TT, UT AND CR.  CALLERS APPLY THE 1.05
  !  UNDERESTIMATION MULTIPLIER THEMSELVES.

  real :: DPP,BATEM,SI,BAUTBA

  DGFCOB = 1.55986 + 1.01825 * DPP - 0.29342 * ALOG(BATEM)&
       &+ 0.00672*SI - 0.00073*BAUTBA
  return
end function DGFCOB
