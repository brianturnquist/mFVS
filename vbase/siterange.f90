!====================================================!
!   Return native species and caller site-index ranges !
!====================================================!
! CI, SO, TT, UT, BM $Id$
subroutine SITERANGE(IWHO,IS,SILOW,SIHIGH)
  implicit none

  include 'PRGPRM.f90'

  !  IWHO=1 IS SITSET; IWHO=2 IS REGENT. ONLY BM ALSO ACCEPTS
  !  IWHO=3 FOR HTGF. OTHER MODES RETURN THE ORIGINAL 0/999 DEFAULTS
  !  BEFORE READING A SPECIES INDEX. UT RETAINS REGENT'S AGE-BASIS BANK.

  integer :: IWHO,IS
  real    :: SILOW,SIHIGH
  real    :: SITELOCI(19),SITEHICI(19)
  real    :: SITELOSO(33),SITEHISO(33)
  real    :: SITELOTT(18),SITEHITT(18)
  real    :: SITELOUT(24),SITEHIUT(24)
  real    :: SITELOBM(18),SITEHIBM(18)
  real    :: SLOUT(24),SHIUT(24)

  !  CI NATIVE RANGES (19 SPECIES).

  ! SUBROUTINE TO RETURN THE SITE INDEX RANGE FOR A SPECIES.
  ! THIS SUBROUTINE IS CALLED FROM **HTGF**,**REGENT**, AND **SITSET**.
  !     SPECIES LIST FOR CENTRAL IDAHO VARIANT.
  !     1 = WESTERN WHITE PINE (WP)          PINUS MONTICOLA
  !     2 = WESTERN LARCH (WL)               LARIX OCCIDENTALIS
  !     3 = DOUGLAS-FIR (DF)                 PSEUDOTSUGA MENZIESII
  !     4 = GRAND FIR (GF)                   ABIES GRANDIS
  !     5 = WESTERN HEMLOCK (WH)             TSUGA HETEROPHYLLA
  !     6 = WESTERN REDCEDAR (RC)            THUJA PLICATA
  !     7 = LODGEPOLE PINE (LP)              PINUS CONTORTA
  !     8 = ENGLEMANN SPRUCE (ES)            PICEA ENGELMANNII
  !     9 = SUBALPINE FIR (AF)               ABIES LASIOCARPA
  !    10 = PONDEROSA PINE (PP)              PINUS PONDEROSA
  !    11 = WHITEBARK PINE (WB)              PINUS ALBICAULIS
  !    12 = PACIFIC YEW (PY)                 TAXUS BREVIFOLIA
  !    13 = QUAKING ASPEN (AS)               POPULUS TREMULOIDES
  !    14 = WESTERN JUNIPER (WJ)             JUNIPERUS OCCIDENTALIS
  !    15 = CURLLEAF MOUNTAIN-MAHOGANY (MC)  CERCOCARPUS LEDIFOLIUS
  !    16 = LIMBER PINE (LM)                 PINUS FLEXILIS
  !    17 = BLACK COTTONWOOD (CW)            POPULUS BALSAMIFERA VAR. TRICHOCARPA
  !    18 = OTHER SOFTWOODS (OS)
  !    19 = OTHER HARDWOODS (OH)
  !  SURROGATE EQUATION ASSIGNMENT:
  !  FROM THE IE VARIANT:
  !      USE 17(PY) FOR 12(PY)             (IE17 IS REALLY TT2=LM)
  !      USE 18(AS) FOR 13(AS)             (IE18 IS REALLY UT6=AS)
  !      USE 13(LM) FOR 11(WB) AND 16(LM)  (IE13 IS REALLY TT2=LM)
  !      USE 19(CO) FOR 17(CW) AND 19(OH)  (IE19 IS REALLY CR38=OH)
  !  FROM THE UT VARIANT:
  !      USE 12(WJ) FOR 14(WJ)
  !      USE 20(MC) FOR 15(MC)             (UT20 = SO30=MC, WHICH IS
  !                                                  REALLY WC39=OT)
  ! Common blocks
  ! Variables
  !  DEFINITION OF VARIABLES:
  !      IS -- FVS SPECIES INDEX NUMBER
  !    IWHO -- 1 IF CALLED FROM SUBROUTINE **SITSET**
  !            2 IF CALLED FROM SUBROUTINE **REGENT**
  !  SITEHI -- UPPER SITE INDEX VALUES
  !  SITELO -- LOWER SITE INDEX VALUES
  !  DATA STATEMENTS:
  !  THESE VALUES SHOULD BE BASED ON THE BASE-AGE OF THE SITE CURVE
  !  BEING USED FOR THAT SPECIES.
  !  SITE INDEX NOT USED FOR THESE SPECIES BUT VALUES ASSIGNED FOR
  !  TRANSLATION TO SPECIES THAT DO USE SITE INDEX:
  !  FROM BM: WP, WL, GF, CW
  !  FROM TT: DF, LP, ES, AF, PP
  !  FROM SO: WH, RC
  !  OS USES DF, OH USES CW

  data SITELOCI/&
       &20.,  50.,  30.,  50.,   6.,  29.,  20.,  40.,  40.,  40.,&
       &25.,  25.,  30.,   5.,   5.,  25.,  30.,  30.,  30./

  data SITEHICI/&
       &80., 110.,  70., 110., 203., 152., 100., 100.,  90.,  80.,&
       &50.,  50.,  70.,  15.,  15.,  50., 120.,  70., 120./

  !  SO NATIVE RANGES (33 SPECIES).

  ! SUBROUTINE TO RETURN THE SITE INDEX RANGE FOR A SPECIES.
  ! THIS SUBROUTINE IS CALLED FROM **HTGF**,**REGENT**, AND **SITSET**.
  !  SPECIES ORDER:
  !  1=WP,  2=SP,  3=DF,  4=WF,  5=MH,  6=IC,  7=LP,  8=ES,  9=SH,  10=PP,
  ! 11=JU, 12=GF, 13=AF, 14=SF, 15=NF, 16=WB, 17=WL, 18=RC, 19=WH,  20=PY,
  ! 21=WA, 22=RA, 23=BM, 24=AS, 25=CW, 26=CH, 27=WO, 28=WI, 29=GC,  30=MC,
  ! 31=MB, 32=OS, 33=OH
  ! Common blocks
  ! Variables
  !  DEFINITION OF VARIABLES:
  !      IS -- FVS SPECIES INDEX NUMBER
  !    IWHO -- 1 IF CALLED FROM SUBROUTINE **SITSET**
  !            2 IF CALLED FROM SUBROUTINE **REGENT**
  !  SITEHI -- UPPER SITE INDEX VALUES
  !  SITELO -- LOWER SITE INDEX VALUES
  !  DATA STATEMENTS:
  !  THESE VALUES SHOULD BE BASED ON THE BASE-AGE OF THE SITE CURVE
  !  BEING USED FOR THAT SPECIES.

  data SITELOSO/&
       &13.,  27.,  21.,   5.,   5.,   5.,   5.,  12.,  10.,   7.,&
       &5.,   9.,   6.,   4.,   7.,  20.,  60.,  29.,   6.,   5.,&
       &5.,  56., 108.,  30.,  10.,  10.,  21.,  20.,   5.,   5.,&
       &5.,   5.,   5./

  data SITEHISO/&
       &137., 178., 148., 195., 133., 169., 140., 227., 134., 176.,&
       &40., 173., 127., 221., 210.,  65., 147., 152., 203.,  75.,&
       &100., 192., 142.,  66., 191., 104.,  85.,  93., 100.,  75.,&
       &75., 175., 125./

  !  TT NATIVE RANGES (18 SPECIES).

  ! SUBROUTINE TO RETURN THE SITE INDEX RANGE FOR A SPECIES.
  ! THIS SUBROUTINE IS CALLED FROM **SITSET** AND **REGENT**.
  ! SPECIES ORDER FOR TETONS VARIANT:
  !  1=WB,  2=LM,  3=DF,  4=PM,  5=BS,  6=AS,  7=LP,  8=ES,  9=AF, 10=PP,
  ! 11=UJ, 12=RM, 13=BI, 14=MM, 15=NC, 16=MC, 17=OS, 18=OH
  ! VARIANT EXPANSION:
  ! BS USES ES EQUATIONS FROM TT
  ! PM USES PI (COMMON PINYON) EQUATIONS FROM UT
  ! PP USES PP EQUATIONS FROM CI
  ! UJ AND RM USE WJ (WESTERN JUNIPER) EQUATIONS FROM UT
  ! BI USES BM (BIGLEAF MAPLE) EQUATIONS FROM SO
  ! MM USES MM EQUATIONS FROM IE
  ! NC AND OH USE NC (NARROWLEAF COTTONWOOD) EQUATIONS FROM CR
  ! MC USES MC (CURL-LEAF MTN-MAHOGANY) EQUATIONS FROM SO
  ! OS USES OT (OTHER SP.) EQUATIONS FROM TT
  ! Common blocks
  ! Variables
  !  DEFINITION OF VARIABLES:
  !      IS -- FVS SPECIES INDEX NUMBER
  !    IWHO -- 1 IF CALLED FROM SUBROUTINE **SITSET**
  !            2 IF CALLED FROM SUBROUTINE **REGENT**
  !  SITEHI -- UPPER SITE INDEX VALUES
  !  SITELO -- LOWER SITE INDEX VALUES
  !  DATA STATEMENTS:
  !  THESE VALUES SHOULD BE BASED ON THE BASE-AGE OF THE SITE CURVE
  !  BEING USED FOR THAT SPECIES.

  data SITELOTT/&
       &25.,  25.,  20.,   5.,  40.,  30.,  20.,  40.,  40.,  40.,&
       &5.,   5.,   5.,   5.,  30.,   5.,  20.,   5./

  data SITEHITT/&
       &50.,  50.,  60.,  20., 100.,  70., 100., 100.,  90.,  80.,&
       &15.,  15.,  30.,  30., 120.,  15.,  50.,  20./

  !  UT NATIVE RANGES (24 SPECIES).

  ! SUBROUTINE TO RETURN THE SITE INDEX RANGE FOR A SPECIES.
  ! THIS SUBROUTINE IS CALLED FROM **SITSET** AND **REGENT**.
  !  SPECIES ORDER:
  !  1=WB,  2=LM,  3=DF,  4=WF,  5=BS,  6=AS,  7=LP,  8=ES,  9=AF, 10=PP,
  ! 11=PI, 12=WJ, 13=GO, 14=PM, 15=RM, 16=UJ, 17=GB, 18=NC, 19=FC, 20=MC,
  ! 21=BI, 22=BE, 23=OS, 24=OH
  ! VARIANT EXPANSION:
  ! GO AND OH USE OA (OAK SP.) EQUATIONS FROM UT
  ! PM USES PI (COMMON PINYON) EQUATIONS FROM UT
  ! RM AND UJ USE WJ (WESTERN JUNIPER) EQUATIONS FROM UT
  ! GB USES BC (BRISTLECONE PINE) EQUATIONS FROM CR
  ! NC, FC, AND BE USE NC (NARROWLEAF COTTONWOOD) EQUATIONS FROM CR
  ! MC USES MC (CURL-LEAF MTN-MAHOGANY) EQUATIONS FROM SO
  ! BI USES BM (BIGLEAF MAPLE) EQUATIONS FROM SO
  ! OS USES OT (OTHER SP.) EQUATIONS FROM UT
  ! Common blocks
  ! Variables
  !  DEFINITION OF VARIABLES:
  !      IS -- FVS SPECIES INDEX NUMBER
  !    IWHO -- 1 IF CALLED FROM SUBROUTINE **SITSET**
  !            2 IF CALLED FROM SUBROUTINE **REGENT**
  !  SITEHI -- UPPER SITE INDEX VALUE FOR SUBROUTINE **SITSET**
  !  SITELO -- LOWER SITE INDEX VALUE FOR SUBROUTINE **SITEST**
  !     SHI -- UPPER SITE INDEX VALUE FOR SUBROUTINE **REGENT**
  !     SLO -- LOWER SITE INDEX VALUE FOR SUBROUTINE **REGENT**
  !  DATA STATEMENTS:
  !  SITE INDEX RANGE VALUES USED IN SUBROUTINE **SITSET**.
  !  THESE VALUES SHOULD BE BASED ON THE BASE-AGE OF THE SITE CURVE
  !  BEING USED FOR THAT SPECIES.
  !  WHEN CHANGING THESE VALUES, ALSO CHANGE THE CORRESPONDING VALUES IN
  !  ARRAYS SLO AND SHI, ADJUSTING VALUES FOR WB, LM, WF, BS, LP, ES, AF,
  !  PP, AND OS AS DIRECTED.

  data SITELOUT/&
       &20.,  20.,  30.,  40.,  40.,  30.,  40.,  40.,  50.,  40.,&
       &5.,   5.,   5.,   5.,   5.,   5.,  20.,  30.,  30.,   5.,&
       &5.,  15.,  20.,   5./

  data SITEHIUT/&
       &50.,  50.,  70.,  80.,  90.,  70.,  85., 100.,  90.,  80.,&
       &20.,  15.,  20.,  20.,  15.,  15.,  60., 120.,  90.,  15.,&
       &30.,  40.,  50.,  20./

  !  SITE INDEX RANGE VALUES USED IN SUBROUTINE **REGENT**.
  !  VALUES HERE FOR WB, LM, WF, BS, LP, ES, AF, PP, AND OS ARE ADJUSTED
  !  TO A 50-YEAR AGE BASIS EQUIVALENT TO THE BASE-AGE BASIS VALUES THAT
  !  APPEAR IN ARRAYS SITELOUT AND SITEHIUT.

  data SLOUT/&
       &15.,  15.,  30.,  20.,  20.,  30.,  27.,  20.,  27.,  23.,&
       &5.,   5.,   5.,   5.,   5.,   5.,  20.,  30.,  30.,   5.,&
       &5.,  15.,  15.,   5./

  data SHIUT/&
       &32.,  32.,  70.,  50.,  58.,  70.,  53.,  65.,  58.,  50.,&
       &20.,  15.,  20.,  20.,  15.,  15.,  60., 120.,  90.,  15.,&
       &30.,  40.,  32.,  20./

  !  BM NATIVE RANGES (18 SPECIES).

  ! SUBROUTINE TO RETURN THE SITE INDEX RANGE FOR A SPECIES.
  ! THIS SUBROUTINE IS CALLED FROM **HTGF**,**REGENT**, AND **SITSET**.
  ! Common blocks
  !  VARIABLE DEFINITIONS:
  !      IS -- FVS SPECIES INDEX NUMBER
  !    IWHO -- 1 IF CALLED FROM SUBROUTINE **SITSET**
  !            2 IF CALLED FROM SUBROUTINE **REGENT**
  !            3 IF CALLED FROM SUBROUTINE **HTGF**
  !  SITEHI -- UPPER SITE INDEX VALUES
  !  SITELO -- LOWER SITE INDEX VALUES
  ! Variables
  !  DATA STATEMENTS
  !  SPECIES ORDER:
  !   1=WP,  2=WL,  3=DF,  4=GF,  5=MH,  6=WJ,  7=LP,  8=ES,
  !   9=AF, 10=PP, 11=WB, 12=LM, 13=PY, 14=YC, 15=AS, 16=CW,
  !  17=OS, 18=OH
  !  SPECIES EXPANSION:
  !  WJ USES SO JU (ORIGINALLY FROM UT VARIANT; REALLY PP FROM CR VARIANT)
  !  WB USES SO WB (ORIGINALLY FROM TT VARIANT)
  !  LM USES UT LM
  !  PY USES SO PY (ORIGINALLY FROM WC VARIANT)
  !  YC USES WC YC
  !  AS USES SO AS (ORIGINALLY FROM UT VARIANT)
  !  CW USES SO CW (ORIGINALLY FROM WC VARIANT)
  !  OS USES BM PP BARK COEFFICIENT
  !  OH USES SO OH (ORIGINALLY FROM WC VARIANT)
  !  THESE VALUES SHOULD BE BASED ON THE BASE-AGE OF THE SITE CURVE
  !  BEING USED FOR THAT SPECIES.

  data SITELOBM/&
       &20.,  50.,  50.,  50.,  15.,   5.,  30.,  40.,  50.,  70.,&
       &20.,  20.,   5.,  50.,  30.,  10.,  70.,   5./

  data SITEHIBM/&
       &80., 110., 110., 110.,  30.,  40.,  70., 120., 150., 140.,&
       &65.,  50.,  75., 110.,  66., 191., 140., 125./

  SILOW = 0.
  SIHIGH = 999.
  if (IWHO.ne.1.and.IWHO.ne.2) then
     if (VARIANTCD.ne.'BM'.or.IWHO.ne.3) return
  end if

  !  EACH BUILD READS ONLY ITS ORIGINAL NATIVE TABLE EXTENT.

  select case (VARIANTCD)
  case ('CI')
     SILOW = SITELOCI(IS)
     SIHIGH = SITEHICI(IS)
  case ('SO')
     SILOW = SITELOSO(IS)
     SIHIGH = SITEHISO(IS)
  case ('TT')
     SILOW = SITELOTT(IS)
     SIHIGH = SITEHITT(IS)
  case ('UT')
     if (IWHO.eq.2) then
        SILOW = SLOUT(IS)
        SIHIGH = SHIUT(IS)
     else
        SILOW = SITELOUT(IS)
        SIHIGH = SITEHIUT(IS)
     end if
  case ('BM')
     SILOW = SITELOBM(IS)
     SIHIGH = SITEHIBM(IS)
  end select

  return
end
