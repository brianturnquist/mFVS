! CANADA-BC $Id$
subroutine NATCRS (TCF,MCF,SCF,BBFV,ISPC,D,H,TKILL,&
     &CRATIO,BARK,ITRNC,VMAX,BFMAX,&
     &RCULL,DECAY,WDSTMS,BIODRYIN,&
     &LIVEDEAD,CTKFLG,BTKFLG,IT)
  implicit none

  !  **THIS VERSION IS A STUB: NATCRS IS NOT USED IN BC**

  !  BC DOES NOT LINK THE NATIONAL CRUISE SYSTEM VOLUME ROUTINES
  !  (vvolume/fvsvol.f90).  THE SHARED FMCROWW (fire/base/fmcroww.f90)
  !  CALLS NATCRS ONLY WHEN VARIANTCD IS NOT 'BC'; THIS STUB SATISFIES
  !  THAT REFERENCE AT LINK TIME AND IS NEVER CALLED.  ITS ARGUMENT LIST
  !  MATCHES THE NATCRS ENTRY IN vvolume/fvsvol.f90.

  ! Variables
  real    :: TCF,MCF,SCF,BBFV,D,H,BARK,VMAX,BFMAX,RCULL,BIODRYIN(15)
  integer :: ISPC,CRATIO,ITRNC,DECAY,WDSTMS,IT
  logical :: TKILL,CTKFLG,BTKFLG
  character(len=1) :: LIVEDEAD
  real    :: RDANUW
  integer :: IDANUW
  logical :: LDANUW
  character(len=1) :: CDANUW

  !  DUMMY ARGUMENT NOT USED WARNING SUPPRESSION SECTION

  if (.true.) return
  RDANUW = TCF
  RDANUW = MCF
  RDANUW = SCF
  RDANUW = BBFV
  IDANUW = ISPC
  RDANUW = D
  RDANUW = H
  LDANUW = TKILL
  IDANUW = CRATIO
  RDANUW = BARK
  IDANUW = ITRNC
  RDANUW = VMAX
  RDANUW = BFMAX
  RDANUW = RCULL
  IDANUW = DECAY
  IDANUW = WDSTMS
  RDANUW = BIODRYIN(1)
  CDANUW = LIVEDEAD
  LDANUW = CTKFLG
  LDANUW = BTKFLG
  IDANUW = IT
  return
end
