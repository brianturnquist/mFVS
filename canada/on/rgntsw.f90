subroutine RGNTSW(LESTB,ITRNIN)
  implicit none

  !  THIS SUBROUTINE PREDICTS DIAMETER AND HT GROWTH FOR SOFTWOODS THAT
  !  HAVE A DIAMETER OF 1.0 INCH OR LESS.  DESPITE THE NAME, THIS
  !  ROUTINE COMPUTES BOTH SOFTWOOD AND HARDWOOD GROWTH.

  !  **REGENT** COMPUTES HEIGHT AND DIAMETER INCREMENTS FOR SMALL
  !  TREES.  THE HEIGHT INCREMENT MODEL AND DBH INCREMENT MODEL ARE
  !  APPLIED TO TREES THAT ARE LESS THAN 1.0 INCH DIAMETER.  FOR TREES
  !  THAT ARE GREATER THAN 0.5 INCH DBH, HEIGHT INCREMENT PRDICTIONS
  !  ARE AVERAGED WITH THE PREDICTIONS FROM THE LARGE TREE MODEL.
  !  HEIGHT INCREMENT IS A FUNCTION OF HABITAT TYPE, SLOPE, ASPECT, TREE
  !  HEIGHT, BASAL AREA IN LARGER TREES, AND STAND CROWN COMPETITION
  !  FACTOR.  DIAMETER IS ASSIGNED FROM A HEIGHT DIAMETER FUNCTION WITH
  !  ADJUSTMENTS FOR RELATIVE SIZE AND STAND DENSITY.  INCREMENT IS
  !  COMPUTED BY SUBTRACTION.  **REGENT** IS CALLES FROM **CRATET** DURING
  !  CALIBRATION AND FROM **GRINCR* DURING CYCLING.  ENTRY **REGCON**
  !  IS CALLED FROM **RCON** TO LOAD MODEL PARAMETERS THAT NEED ONLY BE
  !  RESOLVED ONCE.

  !  **REGENT** IS ALSO USED TO PREDICT HEIGHT INCREMENT, DBH AND CROWN
  !  RATIO FOR TREES THAT ARE CREATED BY THE REGENERATION ESTABLISHMENT
  !  MODEL.  5-YEAR OLD TREES ARE GENERATED BY **ESTAB** AND **REGENT**
  !  COMPUTES INCREMENTS FROM AGE 5 TO THE END OF THE CYCLE.

  ! Common blocks
  include 'PRGPRM.f90'
  include 'CALCOM.f90'
  include 'ARRAYS.f90'
  include 'COEFFS.f90'
  include 'CONTRL.f90'
  include 'OUTCOM.f90'
  include 'PLOT.f90'
  include 'HTCAL.f90'
  include 'MULTCM.f90'
  include 'ESTCOR.f90'
  include 'VARCOM.f90'
  include 'METRIC.f90'

  !  DIMENSIONS FOR INTERNAL VARIABLES:

  !   BANEXT -- ESTIMATED STAND BASAL AREA AT START OF EACH HEIGHT INCREMENT
  !             PREDICTION SUBCYCLE.
  !   CORTEM -- A TEMPORARY ARRAY FOR PRINTING CORRECTION TERMS.
  !     KPER -- NUMBER OF YEARS (MAX OF 5) IN EACH HEIGHT INCREMENT PREDICTION
  !             SUBCYCLE.
  !   NUMCAL -- A TEMPORARY ARRAY FOR PRINTING NUMBER OF HEIGHT
  !             INCREMENT OBSERVATIONS BY SPECIES.
  !   RDNEXT -- RELATIVE DENSITY (CCF) AT START OF EACH HEIGHT INCREMENT
  !             PREDICTION SUBCYCLE.
  !    RHCON -- CONSTANT FOR THE HEIGHT INCREMENT MODEL.  INCLUDES EFFECTS
  !             OF SPECIES, LOCATION, SLOPE, AND ASPECT AS LOADED IN
  !             RCON.
  !     XMAX -- UPPER END OF THE RANGE OF DIAMETERS OVER WHICH HEIGHT
  !             INCREMENT PREDICTIONS FROM SMALL AND LARGE TREE MODELS
  !             ARE AVERAGED.
  !     XMIN -- LOWER END OF THE RANGE OF DIAMETERS OVER WHICH HEIGHT
  !             INCREMENT PREDICTIONS FROM THE SMALL AND LARGE TREE
  !             ARE AVERAGED.

  !     NUMBER OF SMALL TREE HEIGHT GROWTH EQUATIONS

  ! Variables
  logical :: DEBUG,LESTB,LSKIPH
  integer :: ITRNIN
  integer :: I,J,K,L,IYR,NTYR,NPER,ITOT,N
  integer :: IS,NYR,KY,ISPC,I1,I2,I3
  integer :: KPER(10)
  real    :: REGYR,HSIGMA,BACON,BAJ,RDJ,CON
  real    :: SCALE,D1,D2,P,B1,B2,C1,C2,CW,BI,CI
  real    :: PN,BAYR,CCFYR,BARK,SIM
  real    :: XMX,XMN,H1,BAL
  real    :: H,HK,D,H2,DGJ
  real    :: ZZRAN,HTGR,XWT,NEWDBH,HTG2
  real    :: XRDGRO,XRHGRO,DK,DDS,DGK,HTGR1
  real    :: XMAX(MAXSP),XMIN(MAXSP),DIAM(MAXSP)
  real    :: BANEXT(10),RDNEXT(10)

  real    :: BACHLO,BRATIO
  external RANN

  ! Data statements
  data DIAM/2*0.3,0.2,11*0.3,54*0.2,4*0.3/
  data XMIN / MAXSP*3.15 /, XMAX/ MAXSP*4.72 /

  data REGYR  /1.0/ ! Standard regen period is 5 yrs
  data HSIGMA /0.3819/ ! root of the average MSE (klunky)
  data BACON  /0.005454154/

  !  CHECK FOR DEBUG.

  call DBCHK (DEBUG,'RGNTSW',6,ICYC)
  if (DEBUG) write(JOSTND,9980)ICYC
  9980 format(' ENTERING SUBROUTINE RGNTSW CYCLE =',I5)

  !  IF THIS IS THE FIRST CALL TO REGENT, BRANCH TO STATEMENT 40 FOR
  !  MODEL CALIBRATION.

  if (LSTART) goto 40
  call MULTS (3,IY(ICYC),XRHMLT)
  call MULTS(6,IY(ICYC),XRDMLT)
  if (ITRN.le.0) go to 91

  !  THE SMALL TREE HEIGHT INCREMENT MODEL IS BASED ON 5-YEAR INCREMENT DATA.
  !  TO AVOID BIAS, PREDICTIONS ARE MADE FOR SUBCYCLES THAT ARE LESS THAN OR
  !  EQUAL TO 5 YEARS IN LENGTH.  THE FOLLOWING CODE DETERMINES THE NUMBER
  !  AND LENGTH OF SUBCYCLES FROM CYCLE LENGTH.

  LSKIPH = .false.
  do I = 1,10
     KPER(I) = 0
     BANEXT(I) = 0.0
     RDNEXT(I) = 0.0
  end do

  NTYR = INT(FINT)
  if (LSTART) NTYR = IFINTH
  if (LESTB) NTYR = NTYR-5
  if (LESTB.and.NTYR.le.0) LSKIPH = .true.
  IYR = INT(REGYR)
  NPER = NTYR/IYR
  if (MOD(NTYR,IYR).ne.0) NPER = NPER+1
  ITOT = NTYR
  N = NPER
  do I = 1,NPER
     if (N.eq.1) goto 3
     KPER(I) = ITOT/N
     ITOT = ITOT-KPER(I)
     N = N-1
  end do
  3 if (NPER.gt.0) KPER(NPER) = ITOT

  SCALE = YR/FINT
  if (DEBUG) write(JOSTND,8996) LESTB,LSKIPH,ITRN,ITRNIN,SCALE
  8996 format(' IN RGNTSW, LESTB = ',L1,', LSKIPH = ',L1,&
       &', ITRN = ',I4,', ITRNIN = ',I4,', SCALE = ',F6.3)

  !     ESTIMATE THE CONTRIBUTION TO STAND BASAL AREA AND CCF FOR LARGE TREES AT
  !     THE START OF EACH PROJECTION SUBCYCLE.  IF CALLED FROM **ESTAB**, BRANCH
  !     TO STATEMENT 9 AND INTERPOLATE FROM OLD AND NEW DENSITY VALUES.
  !     OTHERWISE, 10-YEAR CHANGE IS COMPUTED FROM PREDICTED DBH INCREMENT AND
  !     ANNUALIZED.  THEN, ANNUAL RATE IS MULTIPLIED BY SUBCYCLE LENGTH TO
  !     DETERMINE CONTRIBUTION FOR EACH SUBCYCLE.  A ONE PERCENT ANNUAL RATE
  !     OF MORTALITY IS ASSUMED.  CONTRIBUTIONS OF SMALL TREES ARE COMPUTED AS
  !     INCREMENT PREDICTIONS ARE MADE FOR PRECEDING SUBCYCLE.

  if (LESTB) goto 9
  do J = 1,NPER
     BANEXT(J) = BA
     RDNEXT(J) = RELDEN
  end do
  if (NPER.eq.1) goto 12
  do I = 1,ITRN
     D1 = DBH(I)
     if (D1.lt.3.0) goto 6
     IS = ISP(I)
     P = PROB(I)
     D2 = D1+DG(I)/BKRAT(ISP(I))
     B1 = BACON*D1*D1
     B2 = BACON*D2*D2
     call CCFCAL(IS,D1,HT(I),ICR(I),P,.false.,C1,CW,1)
     call CCFCAL(IS,D2,HT(I),ICR(I),P,.false.,C2,CW,1)
     BI = (B2-B1)/10.0
     CI = (C2-C1)/10.0
     K = 0
     do J = 2,NPER
        K = K+KPER(J-1)
        PN = P*0.99**K
        RDNEXT(J) = RDNEXT(J)+K*CI
        BANEXT(J) = BANEXT(J)+K*BI*PN
     end do
  6 end do
  goto 12

  !     IF CALLED FROM **ESTAB**, DIAMETERS AND DENSITY STATISTICS HAVE
  !     BEEN UPDATED AND DENSITIES CORRESPONDING TO BEGINNINGS OF SUBCYCLES
  !     CAN BE INTERPOLATED FROM DIFFERENCE BETWEEN OLD AND NEW STATS.  THE
  !     TREES ARE SENT TO REGENT WITH A HEIGHT CORRESPONDING TO 5 YEARS AFTER
  !     THE START OF THE CYCLE.

  9 continue
  BAYR = 0.0
  CCFYR = 0.0
  if (LSKIPH) goto 10
  BAYR = (BA-ATBA)/ITOT
  CCFYR = (RELDEN-ATCCF)/ITOT
  10 continue
  NYR = 5
  do J = 1,NPER
     RDNEXT(J) = ATCCF+NYR*CCFYR
     BANEXT(J) = ATBA+NYR*BAYR
     NYR = NYR+KPER(J)
  end do
  12 continue

  !     STORE INITIAL HEIGHTS IN WK3

  do I = 1,ITRN
     WK3(I) = HT(I)
  end do

  !     ENTER LOOP FOR NEXT SUBCYCLE.

  KY = 0
  do J = 1,NPER !17 LOOP

     KY = KY+KPER(J)
     BAJ = BANEXT(J)
     RDJ = RDNEXT(J)

     !     PROCESS ALL TREES WITHIN THIS SUBCYCLE IN SPECIES ORDER.  LOAD
     !     SPECIES DEPENDENT CONSTANTS.

     do ISPC = 1,MAXSP ! 16 LOOP

        I1 = ISCT(ISPC,1)
        if (I1.eq.0) goto 16
        I2 = ISCT(ISPC,2)

        XRHGRO = XRHMLT(ISPC)
        XRDGRO = XRDMLT(ISPC)
        CON = RHCON(ISPC)+HCOR(ISPC)
        XMX = XMAX(ISPC)
        XMN = XMIN(ISPC)

        SIM = SITEAR(ISPC) * FTtoM

        !     PROCESS NEXT TREE RECORD.  STORE INTERMEDIATE HEIGHTS IN WK3.

        do I3 = I1,I2

           !     BYPASS INCREMENT CALCULATION IF DBH IS GREATER THAN XMX OR IF
           !     CALL IS FROM **ESTAB** AND TREE SUBSCRIPT IS LESS THAN ITRNIN.

           I = IND1(I3)
           D = DBH(I)
           if (D.ge.XMX) goto 15
           if (LESTB .and. I.lt.ITRNIN) goto 15
           P = PROB(I)
           H1 = WK3(I)
           BAL = BAJ*(100.0-PCT(I))*0.01
           call CCFCAL(ISPC,D,H1,ICR(I),P,.false.,C1,CW,1)
           B1 = BACON*D*D

           ! Penner 2010 annual prediction of height growth (ft/yr)
           call ONSTHG(HTG2, ISPC, D, H1, SITEAR(ISPC), BAL)

           HTG2 = LOG(HTG2 * REGYR)
           H2 = H1 + EXP(HTG2)*(FLOAT(KPER(J))/REGYR)*XRHGRO
           WK3(I) = H2

           !     UPDATE DENSITY FOR NEXT SUBCYCLE.  IF ONLY ONE SUBCYCLE OR
           !     IF INITIAL DBH IS GREATER THAN 3 INCHES, BYPASS DENSITY UPDATE.
           !     DIAMETER IS ADJUSTED FOR DENSITY AND USER-SUPPLIED MULTIPLIER.
           !     INCREMENT IS DETERMINED FROM THE DIFFERENCE BETWEEN COMPUTED
           !     DIAMETERS AND IS BOUNDED TO BE GREATER THAN OR EQUAL TO ZERO.

           D2 = D
           if (J.eq.NPER.or.D.ge.3.0) goto 15
           if (H2.le.4.5) goto 15

           D1 = DIAM(ISPC)
           if (H1.gt.4.5) then
              call ONHTDBH(ISPC,D1,BAJ,H1,RMSQD,NEWDBH)
              D1 = NEWDBH
           end if
           call ONHTDBH(ISPC,D2,BAJ,H2,RMSQD,NEWDBH)
           D2 = NEWDBH
           DGJ = (D2-D1)*XRDGRO
           D2 = D+DGJ

           !     COMPUTE ADJUSTMENT TO STAND BASAL AREA AND CCF FOR NEXT SUBCYCLE.
           !     ASSUME A 1.5 PERCENT ANNUAL MORTALITY RATE.

           call CCFCAL(ISPC,D2,H2,ICR(I),P,.false.,C2,CW,1)
           RDNEXT(J+1) = RDNEXT(J+1)+(C2-C1)*0.985**KY
           BANEXT(J+1) = BANEXT(J+1)+(BACON*D2*D2-B1)*P*0.985**KY

        15 end do

        !     END OF SPECIES LOOP WITHIN SUBCYCLE

     16 end do

     !     END OF SUBCYCLE LOOP.  END OF PERIOD HEIGHT IS STORED IN WK3.

  end do

  !     AFTER LAST SUBCYCLE, COMPUTE ACTUAL HEIGHT INCREMENT FOR FULL CYCLE BY
  !     SUBTRACTION; CONVERT BACK TO LOG SCALE TO ADD IN RANDOM ERROR.

  do ISPC = 1,MAXSP

     I1 = ISCT(ISPC,1)
     if (I1.eq.0) goto 30
     I2 = ISCT(ISPC,2)

     XRDGRO = XRDMLT(ISPC)
     XMX = XMAX(ISPC)
     XMN = XMIN(ISPC)

     do I3 = I1,I2
        I = IND1(I3)
        D = DBH(I)
        if (D.ge.XMX) goto 25
        if (LESTB .and. I.lt.ITRNIN) goto 25
        K = I
        L = 0
        H = HT(I)
        HK = WK3(I)

        !     IF CALLED FROM **ESTAB** AND TOTAL CYCLE LENGTH IS LESS THAN OR EQUAL
        !     TO 5 YEARS, SKIP HEIGHT INCREMENT CALCULATION BUT ASSIGN CR AND DBH.

        if (LSKIPH) then
           HTG(K) = 0
           goto 20
        end if
        HTGR1 = HK-H
        if (HTGR1.lt.0.0) HTGR1 = 0.0

        !     DRAW RANDOM INCREMENT GIVEN EXPECTED VALUE, HTGR, AND STD. DEV.,
        !     HSIGMA.  BOUND DRAW TO (-1.5*SD < ZZRAN < 1.0*SD); IF TRIPLING,
        !     EACH TRIPLE GETS A NEW RANDOM NUMBER.  DO NOT TRIPLE IF CALLING
        !     FROM **ESTAB**.  DO NOT APPLY HEIGHT GROWTH MULTIPLIER; MULTIPLIER
        !     WAS USED DURING SUBCYCLING.

        18 ZZRAN = 0.0
        if (DGSD.ge.1.0) ZZRAN = BACHLO(0.0,1.0,RANN)
        if ((ZZRAN .gt.1.0) .or. (ZZRAN .lt. -1.5)) goto 18
        HTGR = HTGR1*EXP(ZZRAN*HSIGMA)

        !     COMPUTE WEIGHTS FOR THE LARGE AND SMALL TREE HEIGHT INCREMENT
        !     ESTIMATES.  IF DBH IS LESS THAN OR EQUAL TO XMN OR IF CALLED
        !     FROM **ESTAB**, THE LARGE TREE PREDICTION IS IGNORED (XWT=0.0).

        XWT = 0.0
        if (D.le.XMN.or.LESTB) goto 19
        XWT = (D-XMN)/(XMX-XMN)
        19 HTG(K) = HTGR*(1.0-XWT) + XWT*HTG(K)

        !     CHECK FOR SIZE CAP COMPLIANCE.

        if ((H+HTG(K)).gt.SIZCAP(ISPC,4)) then
           HTG(K) = SIZCAP(ISPC,4)-H
           if (HTG(K) .lt.0.1) HTG(K) = 0.1
        end if

        !     ASSIGN DBH AND COMPUTE DBH INCREMENT FOR TREES WITH DBH LESS
        !     THAN 3 INCHES.  COMPUTE 10-YEAR DBH INCREMENT REGARDLESS OF
        !     PROJECTION PERIOD LENGTH.  BYPASS INCREMENT CALCULATION IF
        !     D GE 1.0 INCHES.

        20 if (D.ge.1.0) goto 23

        D1 = DIAM(ISPC)
        if (H.gt.4.5)&
             &call ONHTDBH(ISPC,D,BAJ,H,RMSQD,D1)

        HK = H + HTG(K)
        if (HK.le.4.5) then
           DBH(K) = D + HK*0.001
           DGK = 0.0
           DG(K) = 0.0
        else
           DK = 0.
           call ONHTDBH(ISPC,D,BAJ,HK,RMSQD,DK)
           if (DK.lt.DIAM(ISPC)) DK = DIAM(ISPC)
           DK = DK + HK*0.001

           !     IF CALLING FROM **ESTAB** ASSIGN DIAMETER AND DIAMETER
           !     INCREMENT.

           if (LESTB) then
              DBH(K) = DK
              DG(K) = DK
           else

              !     DIAMETER INCREMENT IS THE DIFFERENCE BETWEEN COMPUTED
              !     DIAMETERS.  MULTIPLIER IS APPLIED TO DIAMETER INCREMENT
              !     AT THIS POINT.

              DGK = (DK-D1)*XRDGRO
              if (DGK.lt.0.0) DGK = 0.0

              !     SCALE DIAMETER INCREMENT FOR BARK AND PERIOD LENGTH.
              !     ADJUSTMENT IN ORDER TO MAINTAIN CONSISTENCY WITH **GRADD**,
              !     ADJUSTMENTS ARE MADE ON THE DDS SCALE.

              BARK = BRATIO(ISPC,DBH(K),H)
              DG(K) = DGK*BARK
              DDS = DG(K)*(2.0*BARK*DK+DG(K))*SCALE
              DG(K) = SQRT((DK*BARK)**2.0+DDS)-BARK*DK
           end if
           if ((DBH(K)+DG(K)).lt.DIAM(ISPC)) then
              DG(K) = DIAM(ISPC)-DBH(K)
           end if
        end if

        !     CHECK FOR TREE SIZE CAP COMPLIANCE

        call DGBND(ISPC,DBH(K),DG(K))

        !     PRINT DEBUG AND RETURN TO PROCESS NEXT TRIPLE OR NEXT TREE.

        23 if (.not.DEBUG) goto 24
        write(JOSTND,9000) I,K,ISPC,H,HTG(K),HK,DBH(K),DG(K),BARK
        9000 format(' IN RGNTSW LOOP 2, I=',I4,', K=',I4,', ISPC=',I3,&
             &', CUR HT=',F7.2,', HT INC=',F7.4/T20,'NEW HT=',F7.2,&
             &', CUR DBH=',F7.2,', 10-YR DBH INC=',F7.4,' ,BARK=',F5.4)
        24 continue

        if (LESTB .or..not.LTRIP .or. L.ge.2) goto 25
        L = L+1
        K = ITRN+2*I-2+L
        goto 18

        !     END OF GROWTH PREDICTION LOOP.  PRINT DEBUG INFO IF DESIRED.

     25 end do
  30 end do
  40 continue

  !     THIS IS A SECTION THAT NEEDS TO BE REVISED TO IMPLEMENT SMALL TREE
  !     SELF-CALIBRATION, WHICH IS NOT YET ACTIVE (20-Mar-2007)

  !C----------
  !C  SMALL TREE HEIGHT CALIBRATION SECTION.
  !C----------
  !      DO 45 ISPC=1,MAXSP
  !      HCOR(ISPC)=0.0
  !      CORTEM(ISPC)=1.0
  !      NUMCAL(ISPC)=0
  !   45 CONTINUE
  !      IF (ITRN.LE.0) GO TO 91
  !      IF(IFINTH .EQ. 0)  GOTO 95
  !C----------
  !C  DETERMINE BASAL AREA IN LARGE TREES AT START OF EACH
  !C  PREDICTION SUBCYCLE.
  !C----------
  !      DO 46 J=1,NPER
  !      BANEXT(J)=ATBA
  !      RDNEXT(J)=ATCCF
  !   46 CONTINUE
  !      IF(NPER.EQ.1) GO TO 50
  !C----------
  !C  IF THERE IS MORE THAN 1 SUBCYCLE FOR HEIGHT INCREMENT PREDICTION,
  !C  (IFINTH > 5) ESTIMATE VALUES OF BA AND RELATIVE DENSITY (CCF) AT
  !C  START OF EACH SUBCYCLE.  10-YEAR CHANGE IS COMPUTED FROM BACKDATED
  !C  DIAMETER (WK3) AND 10-YEAR DIAMETER INCREMENT COMPUTED DURING CALIBRATION.
  !C  LINEAR INTERPOLATION IS USED TO ASSIGN VALUES FOR SUBCYCLES.
  !C----------
  !      DO 49 I=1,ITRN
  !      D1=WK3(I)
  !      IS=ISP(I)
  !      P=PROB(I)
  !      D2=WK3(I)+DG(I)/BRATIO(IS,D1,HT(I))
  !      B1=BACON*D1*D1
  !      B2=BACON*D2*D2
  !      CALL CCFCAL(IS,D1,HT(I),ICR(I),P,.FALSE.,C1,CW,1)
  !      CALL CCFCAL(IS,D2,HT(I),ICR(I),P,.FALSE.,C2,CW,1)
  !      BI=(B2-B1)/10.0
  !      CI=(C2-C1)/10.0
  !      K=0
  !      DO 48 J=2,NPER
  !      K=K+KPER(J-1)
  !      PN=P*0.99**K
  !      RDNEXT(J)=RDNEXT(J)+K*CI*PN
  !      BANEXT(J)=BANEXT(J)+K*BI*PN
  !   48 CONTINUE
  !   49 CONTINUE
  !   50 CONTINUE
  !      DO 100 ISPC=1,MAXSP
  !C----------
  !C  BEGIN PROCESSING TREE LIST IN SPECIES ORDER.  DO NOT CALCULATE
  !C  CORRECTION TERMS IF THERE ARE NO TREES FOR THIS SPECIES.
  !C----------
  !      CORNEW=1.0
  !      I1=ISCT(ISPC,1)
  !      IF(I1.EQ.0 .OR. .NOT. LHTCAL(ISPC)) GO TO 100
  !      I2=ISCT(ISPC,2)
  !      N=0
  !      SNP=0.0
  !      SNX=0.0
  !      SNY=0.0
  !      IREFI=IREF(ISPC)
  !C----------
  !C  COMPUTE RELATIVE SITE INDEX MODIFIER  AND SET SCALE FOR HARDWOODS.
  !C----------
  !      IF(ISPC .GE. 15) THEN
  !        SCALE3 = 10.0 / FINTH
  !        SI=SITEAR(ISPC)
  !        IF(SI .GT. SHI) SI=SHI
  !        IF(SI .LE. SLO) SI=SLO + 0.5
  !        RELSI=(SI-SLO)/(SHI-SLO)
  !        RSIMOD = .5*(RELSI)+.5
  !        IF(DEBUG) WRITE(JOSTND,9988)SI,RELSI,ISPC,RSIMOD
  ! 9988   FORMAT(' IN RGNTHW SI,RELSI,ISPC,RSIMOD = ',
  !     &  F7.2,F10.3,I6,F10.3)
  !      ENDIF
  !C----------
  !C  SET SPECIES CONSTANTS AND SCALE FOR SOFTWOODS.
  !C----------
  !      IF(ISPC .LE. 14) THEN
  !        SCALE3 = 5.0 / FINTH
  !      ENDIF
  !C----------
  !C  BEGIN TREE LOOP WITHIN SPECIES.  IF MEASURED HEIGHT INCREMENT IS
  !C  LESS THAN OR EQUAL TO ZERO, OR DBH IS LESS THAN 5.0, THE RECORD
  !C  WILL BE EXCLUDED FROM THE CALIBRATION.
  !C----------
  !      DO 60 I3=I1,I2
  !      I=IND1(I3)
  !      H=HT(I)
  !C----------
  !C  DIA GT 3 INCHES INCLUDED IN OVERALL MEAN
  !C----------
  !      IF(IHTG.LT.2) H=H-HTG(I)
  !      IF(DBH(I).GE.3.0.OR.H.LT.0.01) GO TO 60
  !      IF(ISPC .LE. 14) THEN
  !        HK=H
  !        DO 55 J=1,NPER
  !        BAJ=BANEXT(J)
  !        RDJ=RDNEXT(J)
  !        BAL=BAJ*(100.0-PCT(I))*0.0001
  !        EDH=EXP(BHAB + BLH*ALOG(HK) + BCCF*RDJ + BBAL*BAL)
  !        HK=HK+EDH
  !   55   CONTINUE
  !        EDH=HK-H
  !      ELSE
  !        AG1 = (H*12*2.54/26.9825)**.8509
  !        AG2 = AG1 + 10.
  !        H2 = (26.9825*AG2**1.1752)/(2.54*12.0)
  !        EDH =(H2-H)*RSIMOD*RHCON(ISPC)
  !C----------
  !C  GROWTH RATES APPEAR HIGH, REDUCE BY 25%. DIXON 8-27-92
  !C----------
  !        EDH=EDH*.75
  !C----------
  !C  GET MODIFIER BORROWED FROM THE DIAMETER GROWTH EQUATIONS AND
  !C  ADJUST THE HEIGHT GROWTH ESTIMATE.
  !C----------
  !        CALL BALMOD(ISPC,D,BA,RMSQD,GM,DEBUG)
  !        EDH=EDH*GM
  !        IF(DEBUG)WRITE(JOSTND,*)' I,GM,EDH= ',I,GM,EDH
