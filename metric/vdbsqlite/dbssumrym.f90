!==================================!
!   metric/vdbsqlite : dbssumrym   !
!==================================!
! METRIC-VDBSQLITE $Id$
subroutine DBSSUMRYM(IYEAR,IAGE,NPLT,ITPA,IBA,ISDI,ICCF,&
     &ITOPHT,FQMD,ITCUFT,IMCUFT,IBDFT,IRTPA,IRTCUFT,IRMCUFT,IRBDFT,&
     &IATBA,IATSDI,IATCCF,IATTOPHT,FATQMD,IPRDLEN,IACC,IMORT,YMAI,&
     &IFORTP,ISZCL,ISTCL)
  implicit none

  !     PURPOSE: ARGUMENT ADAPTER FOR THE METRIC VARIANTS (BC, ON).

  !     THE METRIC BRANCH OF VBASE/SUMOUT.F90 PASSES THE 28 ARGUMENTS OF THE
  !     FORMER METRIC DBSSUMRY. DBSSUMRY IN VDBSQLITE/DBSSUMRY.F90 NOW SERVES
  !     ALL VARIANTS AND TAKES 30; ITS METRIC PATH DOES NOT USE ISCUFT AND
  !     IRSCUFT, SO ZEROS ARE PASSED. COMPILED ONLY BY BC AND ON. REMOVE IT
  !     WHEN VBASE/SUMOUT.F90 CALLS DBSSUMRY DIRECTLY WITH THE FULL
  !     ARGUMENT LIST.

  ! Variables
  integer :: IYEAR,IAGE,IPRDLEN,IACC,IMORT,ITPA,IBA,ISDI,ICCF,ITOPHT,ITCUFT,IMCUFT,IBDFT,IRTPA,&
       &IRTCUFT,IRMCUFT,IRBDFT,IATBA,IATSDI,IATCCF,IATTOPHT,IFORTP,ISZCL,ISTCL
  real    :: FQMD,FATQMD,YMAI
  character(len=*) :: NPLT

  call DBSSUMRY(IYEAR,IAGE,NPLT,ITPA,IBA,ISDI,ICCF,&
       &ITOPHT,FQMD,ITCUFT,IMCUFT,0,IBDFT,IRTPA,IRTCUFT,IRMCUFT,0,IRBDFT,&
       &IATBA,IATSDI,IATCCF,IATTOPHT,FATQMD,IPRDLEN,IACC,IMORT,YMAI,&
       &IFORTP,ISZCL,ISTCL)
  return
end
