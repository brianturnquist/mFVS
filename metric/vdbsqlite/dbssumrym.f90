!==================================!
!   metric/vdbsqlite : dbssumrym   !
!==================================!
! METRIC-VDBSQLITE $Id$
subroutine DBSSUMRYM(IYEAR,IAGE,NPLT,ITPA,IBA,ISDI,ICCF,&
     &ITOPHT,FQMD,ITCUFT,IMCUFT,IBDFT,IRTPA,IRTCUFT,IRMCUFT,IRBDFT,&
     &IATBA,IATSDI,IATCCF,IATTOPHT,FATQMD,IPRDLEN,IACC,IMORT,YMAI,&
     &IFORTP,ISZCL,ISTCL)
  implicit none

  !     PURPOSE: PASS-THROUGH TO THE METRIC (BC, ON) DBSSUMRY IN
  !              METRIC/VDBSQLITE/DBSSUMRY.F90.

  !     THE METRIC DBSSUMRY TAKES 28 ARGUMENTS AND THE IMPERIAL ONE
  !     (VDBSQLITE/DBSSUMRY.F90) TAKES 30. VBASE/SUMOUT.F90 IS SHARED BY
  !     ALL VARIANTS AND NEEDS BOTH CALLS, BUT ONE FILE CANNOT CALL THE
  !     SAME EXTERNAL WITH TWO ARGUMENT LISTS, SO ITS METRIC BRANCH CALLS
  !     THIS ROUTINE INSTEAD. COMPILED ONLY BY BC AND ON. REMOVE IT WHEN
  !     THE TWO DBSSUMRY ROUTINES SHARE ONE ARGUMENT LIST.

  ! Variables
  integer :: IYEAR,IAGE,IPRDLEN,IACC,IMORT,ITPA,IBA,ISDI,ICCF,ITOPHT,ITCUFT,IMCUFT,IBDFT,IRTPA,&
       &IRTCUFT,IRMCUFT,IRBDFT,IATBA,IATSDI,IATCCF,IATTOPHT,IFORTP,ISZCL,ISTCL
  real    :: FQMD,FATQMD,YMAI
  character(len=*) :: NPLT

  call DBSSUMRY(IYEAR,IAGE,NPLT,ITPA,IBA,ISDI,ICCF,&
       &ITOPHT,FQMD,ITCUFT,IMCUFT,IBDFT,IRTPA,IRTCUFT,IRMCUFT,IRBDFT,&
       &IATBA,IATSDI,IATCCF,IATTOPHT,FATQMD,IPRDLEN,IACC,IMORT,YMAI,&
       &IFORTP,ISZCL,ISTCL)
  return
end
