!=================================!
!   metric/dbsqlite : dbsstatsm   !
!=================================!
! METRIC-DBSQLITE $Id$
subroutine DBSSTATSM(SPECCD,TPA,BAREA,CFVOL,BFVOL,STDIST1,&
     &STDIST2,STDIST3,STDIST4,STDIST5,STDIST6,STDIST7,STDIST8,&
     &STDIST9,LABEL,TBL,IYEAR)
  implicit none

  !     PURPOSE: PASS-THROUGH TO THE METRIC (BC, ON) DBSSTATS IN
  !              METRIC/DBSQLITE/DBSSTATS.F90.

  !     THE METRIC DBSSTATS TAKES 17 ARGUMENTS AND THE IMPERIAL ONE
  !     (DBSQLITE/DBSSTATS.F90) TAKES 19. BASE/STATS.F90 IS SHARED BY ALL
  !     VARIANTS AND NEEDS BOTH CALLS, BUT ONE FILE CANNOT CALL THE SAME
  !     EXTERNAL WITH TWO ARGUMENT LISTS, SO ITS METRIC BRANCH CALLS THIS
  !     ROUTINE INSTEAD. COMPILED ONLY BY BC AND ON. REMOVE IT WHEN THE
  !     TWO DBSSTATS ROUTINES SHARE ONE ARGUMENT LIST.

  ! Variables
  integer :: TBL,IYEAR
  real    :: STDIST1,STDIST2,STDIST3,STDIST4,STDIST5
  real    :: STDIST6,STDIST7,STDIST8,STDIST9
  real    :: TPA,BAREA,CFVOL,BFVOL
  character(len=*) :: SPECCD
  character(len=*) :: LABEL

  call DBSSTATS(SPECCD,TPA,BAREA,CFVOL,BFVOL,STDIST1,&
       &STDIST2,STDIST3,STDIST4,STDIST5,STDIST6,STDIST7,STDIST8,&
       &STDIST9,LABEL,TBL,IYEAR)
  return
end
