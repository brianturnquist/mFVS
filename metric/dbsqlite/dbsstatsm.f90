!=================================!
!   metric/dbsqlite : dbsstatsm   !
!=================================!
! METRIC-DBSQLITE $Id$
subroutine DBSSTATSM(SPECCD,TPA,BAREA,CFVOL,BFVOL,STDIST1,&
     &STDIST2,STDIST3,STDIST4,STDIST5,STDIST6,STDIST7,STDIST8,&
     &STDIST9,LABEL,TBL,IYEAR)
  implicit none

  !     PURPOSE: ARGUMENT ADAPTER FOR THE METRIC VARIANTS (BC, ON).

  !     THE METRIC BRANCH OF BASE/STATS.F90 PASSES THE 17 ARGUMENTS OF THE
  !     FORMER METRIC DBSSTATS (NO BIOMASS OR CARBON). DBSSTATS IN
  !     DBSQLITE/DBSSTATS.F90 NOW SERVES ALL VARIANTS AND TAKES 19; ITS
  !     METRIC PATH DOES NOT USE AGBIO AND AGCARB, SO ZEROS ARE PASSED.
  !     COMPILED ONLY BY BC AND ON. REMOVE IT WHEN BASE/STATS.F90 CALLS
  !     DBSSTATS DIRECTLY WITH THE FULL ARGUMENT LIST.

  ! Variables
  integer :: TBL,IYEAR
  real    :: STDIST1,STDIST2,STDIST3,STDIST4,STDIST5
  real    :: STDIST6,STDIST7,STDIST8,STDIST9
  real    :: TPA,BAREA,CFVOL,BFVOL
  character(len=*) :: SPECCD
  character(len=*) :: LABEL

  call DBSSTATS(SPECCD,TPA,BAREA,CFVOL,BFVOL,0.,0.,STDIST1,&
       &STDIST2,STDIST3,STDIST4,STDIST5,STDIST6,STDIST7,STDIST8,&
       &STDIST9,LABEL,TBL,IYEAR)
  return
end
